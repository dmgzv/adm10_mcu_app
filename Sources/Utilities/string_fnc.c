// Функция преобразования строки до разделителя в беззнаковое целое с проверкой валидности исходных данных
// Аргументы функции:
// str - буфер с числом для преобразования
// pResult - Указатель, куда записать результат преобразования
// cDel - символ разделитель
// функция возвращает результат проверки валидности исходных данных
//=============================================================================
int StrToUint( char *str, unsigned int * pResult, char cDelim )
{
	if( !str ) 
		return 0;
	while( *str == ' ' )
		str++;//отбрасываем лишние пробелы
	*pResult = 0;
	unsigned int dwCnt = 11;//максимальное количество проверяемых символов в строке
	while( --dwCnt )
	{
		char ch = *str;
		if( ch < '0' || ch > '9' )
			break;// число закончилось, выходим
		if( *pResult > 429496729 || ( *pResult == 429496729 && ch > '5' ) )
			return 0;//число за рамками беззнакового целого, выходим с ошибкой
		*pResult *= 10;
		*pResult += ch - '0';
		str++;
	}
	while( *str == ' ' )
		str++;//отбрасываем лишние пробелы
	return dwCnt < 10 /*&& ( *str == cDelim || *str == 0 )*/;// проверяем что всё число преобразовали до разделителя или конца строки, иначе ошибка
}
