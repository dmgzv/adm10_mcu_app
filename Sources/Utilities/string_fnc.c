char * IntToStr( char * str, int iVal )
{
	if( !str )
		return str;
	// просто печатаем сначала знак, а затем оставшееся как беззнаковое
	if( iVal < 0 )
	{	
		*str++ = '-';
		iVal = -iVal;
	}
	str = UintToStr( str, (unsigned int)iVal );
	return str;
}
