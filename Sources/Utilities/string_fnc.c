char * FloatToStr( char * str, float f, unsigned int dwDigCount )
{
	if( !str )
		return str;

	char * pStartStr = str;

	// коэффициенты для каждго из возможных количеств знаков после десятичной точки
	static const long iCoefTab[ 10 ] = { 1, 10, 100, 1000, 10000, 100000, 1000000, 10000000, 100000000, 1000000000 };
	long iVal = f * iCoefTab[ dwDigCount ];// преобразуем в целое, чтоб его напечатать

	if( iVal < 0 )//печатаем знак, далее будет беззнаковое
	{	
		*str++ = '-';
		iVal = -iVal;
	}

	unsigned int dwVal = iVal;
  unsigned int dwDig, dwPrint, dwDigIndex;
	dwPrint = 0;
//алгоритм разбиваем на 2 этапа 1..99999 и 100000..макс32бит
	if( dwVal > 99999 || dwDigCount > 5 )
	{
		dwDigIndex = 10;//текущий идекс знака
		unsigned int dwVal1 = dwVal / 100000;//готовим старшие десятичные разряды для перобразования
		dwVal -= dwVal1 * 100000;

		//быстрый алгоритм, основанный специальном множителе, приводящем к десятичному представлению старшего разряда в стрших 4 битах 32 битного беззнакового целого
		dwVal1 *= 26844;
		for( unsigned int i = 0; i < 5; i++ )
		{
			if( dwDigIndex == dwDigCount )
				*str++ = '.';//печатаем точку, как придёт время
			if( --dwDigIndex <= dwDigCount )
				dwPrint = 1;
			dwDig = dwVal1 >> 28;
			if( dwDig || dwPrint )//нули печатаем, если только какое либо ненулевое значение уже напечатано
			{
					*str++ = dwDig + '0';
					dwPrint = 1;
			}
			dwVal1 &= 0x0FFFFFFF;
			dwVal1 *= 10;
		}
	}

	//быстрый алгоритм, основанный специальном множителе, приводящем к десятичному представлению старшего разряда в стрших 4 битах 32 битного беззнакового целого
	dwDigIndex = 5;//текущий идекс знака
	// в алгоритме есть выколотая точка, учитываем её особым образом
	if( dwVal == 59075 ) 
	{
		if( dwDigIndex-- == dwDigCount ) *str++ = '.';
		*str++ = '5';
		if( dwDigIndex-- == dwDigCount ) *str++ = '.';
		*str++ = '9';
		if( dwDigIndex-- == dwDigCount ) *str++ = '.';
		*str++ = '0';
		if( dwDigIndex-- == dwDigCount ) *str++ = '.';
		*str++ = '7';
		if( dwDigIndex-- == dwDigCount ) *str++ = '.';
		*str++ = '5';
		*str = 0;
		return str;
	}
	if( dwVal > 59075 )
		dwVal--;
	//основная часть алгоритма для оставшихся младших десятичных разрядов
  dwVal *= 26844;
	for( unsigned int i = 0; i < 5; i++ )
	{
		if( dwDigIndex == dwDigCount )
			*str++ = '.';//печатаем точку, как придёт время
		if( --dwDigIndex <= dwDigCount )
			dwPrint = 1;
		dwDig = dwVal >> 28;
		if( dwDig || dwPrint )//нули печатаем, если только какое либо ненулевое значение уже напечатано
		{
				*str++ = dwDig + '0';
				dwPrint = 1;
		}
		dwVal &= 0x0FFFFFFF;
		dwVal *= 10;
	}
	if( str == pStartStr )
	{
		*str++ = '0';
		*str = 0;
	}// ничего не напечатали, значит 0
	*str = 0;//конец строки
	
	return  str;
}
