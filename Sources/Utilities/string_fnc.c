// Функция преобразования беззнакового целого в hex строку с возвратом указателя на конец строки 
// Аргументы функции:
// str - буфер для печати строки
// dwVal - Печатаемое значение
// функция возвращает указатель на конец строки
//=============================================================================
char * UintToHexStr( char * str, unsigned int dwVal )
{
	if( !str )
		return str;
	char * pch = &str[ 7 ];
	unsigned char by;
	// просто последовательно печатаем со старшего разряда до младшего
	while( pch >= str )
	{
		by = dwVal & 0x0F;
		dwVal >>= 4;
		if( by > 9 )
			*pch-- = ( 'A' - 10 ) + by;
		else
			*pch-- = '0' + by;
	}
	pch += 9;
	*pch = 0;//конец строки
	return pch;
}
