// Функция преобразования hex строки до разделителя в знаковое целое с проверкой валидности исходных данных
// Аргументы функции:
// str - буфер с числом для преобразования
// pResult - Указатель, куда записать результат преобразования
// cDel - символ разделитель
// функция возвращает результат проверки валидности исходных данных
//=============================================================================
int HexStrToUint( char* str, unsigned int * pResult, char cDel )
{
	*pResult = 0;
	if( !str )
		return 0;
	unsigned int dwCnt = 8;//максимальное количество проверяемых символов в строке
	while( dwCnt-- ) 
	{
		char ch = *str++;
		if( ch >= '0' && ch <= '9' )
			ch -= '0';
		else if( ch >= 'A' && ch <= 'F' )
			ch -= 'A' - 10;
		else if( ch >= 'a' && ch <= 'f' )
			ch -= 'a' - 10;
		else
			return ch == cDel;//число закончилось, выходим
		*pResult <<= 4;
		*pResult += ch;
	}
	return *str == cDel;// проверяем, что дошли до разделителя.
}
