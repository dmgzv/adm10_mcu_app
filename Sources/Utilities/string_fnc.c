// выполняется максимум 3мксек на STM32F207
// Аргументы функции:
// str - буфер для печати строки
// byVal - Печатаемое значение
// функция возвращает указатель на конец строки
//=============================================================================
char * ByteToStr( char * str, unsigned char byVal )
{
	if( !str ) 
		return str;
	char * pStartStr = str;
  unsigned int dwDig, dwPrint;
	dwPrint = 0;
	unsigned int dwVal = byVal;

	//быстрый алгоритм, основанный специальном множителе, приводящем к десятичному представлению старшего разряда в стрших 4 битах 32 битного беззнакового целого
	dwVal *= 2684400;
	for( unsigned int i = 0; i < 3; i++ )
	{
			dwDig = dwVal >> 28;
			if( dwDig || dwPrint )//нули печатаем, если только какое либо ненулевое значение уже напечатано
			{
					*str++ = dwDig + '0';
					dwPrint = 1;
			}
			dwVal &= 0x0FFFFFFF;
			dwVal *= 10;
	}
	if( str == pStartStr )
	{
		*str++ = '0';
		*str = 0;
	}// ничего не напечатали, значит 0
	*str = 0;//конец строки
	return str;
}
