int StrToIP( char * str, unsigned int *pResult )
{
	int i;
	unsigned int ip[4];
	
	for( i = 0; i < 3; i++ )// преобразуем каждый из 4 байтов разделённых "."
	{
		if( !StrToUint( str, &ip[ i ], '.' ))// преобразование с проверкой формата )
			return 0;// проверка корректности строкового представления в звпросе и преобразование в число
		str = strchr( str, '.' ) + 1;
	}
	if( !StrToUint( str, &ip[ 3 ], '.' ))// преобразование с проверкой формата )
		return 0;// проверка корректности строкового представления в звпросе и преобразование в число
	for( i = 0; i < 4; i++ )// проверяем диапазон - байты
	{
		if( ip[ i ] > 255 )
			return 0;// проверка корректности строкового представления в звпросе и преобразование в число
	}			
	*pResult = ip[0] | (ip[1] << 8) | (ip[2] << 16) | (ip[3] << 24);
	return 1;
}
