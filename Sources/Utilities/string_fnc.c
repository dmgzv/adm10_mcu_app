int HexStr2ToByte( char * str, unsigned char * pResult )
{
	*pResult = 0;
	if( !str )
		return 0;
	unsigned int dwCnt = 2;//количество проверяемых символов в строке
	while( dwCnt-- ) 
	{
		char ch = *str++;
		*pResult <<= 4;
		if( ch >= '0' && ch <= '9' )
			*pResult += ch - '0';
		else if( ch >= 'A' && ch <= 'F' )
			*pResult += ch - 'A' + 10;
		else if( ch >= 'a' && ch <= 'f' )
			*pResult += ch - 'a' + 10;
		else
			return 0;
	}
	return 1;
}
