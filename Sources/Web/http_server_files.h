#ifndef __HTTP_SERVER_FILES_H__
#define __HTTP_SERVER_FILES_H__

#include "bsp_flash.h"

#define HTTP_SERVER_FILES_DATA_TYPE_HTML	0
#define HTTP_SERVER_FILES_DATA_TYPE_JS		1
#define HTTP_SERVER_FILES_DATA_TYPE_CSS		2
#define HTTP_SERVER_FILES_DATA_TYPE_WOFF2	3
#define HTTP_SERVER_FILES_DATA_TYPE_JSON	4
#define HTTP_SERVER_FILES_DATA_TYPE_BIN		5

#define HTTP_SERVER_FILES_RECORDS_ADDR	( BSP_FLASH_WEB_ADDR )
#define	HTTP_SERVER_FILES_RECORDS_SIZE	(	BSP_FLASH_WEB_SIZE )
#define	HTTP_SERVER_FILES_RECORDS_PAGES	(	HTTP_SERVER_FILES_RECORDS_SIZE / BSP_FLASH_PAGE_SIZE )
#define HTTP_SERVER_FILES_RECORDS_CNT		( 2 )

#define HTTP_SERVER_FILES_RECORD_ADDR(RecordIdx)	( HTTP_SERVER_FILES_RECORDS_ADDR + ((RecordIdx) * HTTP_SERVER_FILES_RECORD_SIZE) )
#define	HTTP_SERVER_FILES_RECORD_SIZE							(	HTTP_SERVER_FILES_RECORDS_SIZE / HTTP_SERVER_FILES_RECORDS_CNT )
#define	HTTP_SERVER_FILES_RECORD_PAGES						(	HTTP_SERVER_FILES_RECORD_SIZE / BSP_FLASH_PAGE_SIZE )

#define HTTP_SERVER_FILES_RECORD_HEADER_ADDR(RecordIdx)	( HTTP_SERVER_FILES_RECORD_ADDR(RecordIdx) )
#define	HTTP_SERVER_FILES_RECORD_HEADER_SIZE						(	HTTP_SERVER_FILES_RECORD_HEADER_PAGES * BSP_FLASH_PAGE_SIZE )
#define	HTTP_SERVER_FILES_RECORD_HEADER_PAGES						(	1 )

#define HTTP_SERVER_FILES_RECORD_BODY_ADDR(RecordIdx)	( HTTP_SERVER_FILES_RECORD_ADDR(RecordIdx) + HTTP_SERVER_FILES_RECORD_HEADER_SIZE )
#define	HTTP_SERVER_FILES_RECORD_BODY_SIZE						(	HTTP_SERVER_FILES_RECORD_SIZE - HTTP_SERVER_FILES_RECORD_HEADER_SIZE )
#define	HTTP_SERVER_FILES_RECORD_BODY_PAGES						(	HTTP_SERVER_FILES_RECORD_PAGES - HTTP_SERVER_FILES_RECORD_HEADER_PAGES )

void HTTP_SERVER_FILES_Init(void);
int32_t HTTP_SERVER_FILES_FindByName(char *Name, uint32_t NameLen, uint32_t *DataAddr, uint32_t *DataSize, uint32_t *DataType);
int32_t HTTP_SERVER_FILES_ReadData(uint32_t DataAddr, char *Data, uint32_t DataSize);
int32_t HTTP_SERVER_FILES_ReadDataSize(uint32_t *DataSize);
int32_t HTTP_SERVER_FILES_WriteData(uint32_t DataAddr, char *Data, uint32_t DataSize);
int32_t HTTP_SERVER_FILES_WriteDataSize(uint32_t DataSize);

#endif /* __HTTP_SERVER_FILES_H__ */
