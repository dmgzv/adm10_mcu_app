#ifndef __MT48LC16M16A2_H
#define __MT48LC16M16A2_H

/* Includes ------------------------------------------------------------------*/
#include "stm32f4xx_hal.h"
#include "bsp_config.h"
#include "bsp_dev.h"
#ifdef BSP_CONFIG_USE_FREERTOS
#include "cmsis_os.h"
#endif

/* Timings for Speed Grade "-6A"*/
#define MT48LC16M16A2_ROWS_CNT	8192
#define MT48LC16M16A2_tRFC	64	/*ms*/
#define MT48LC16M16A2_tMRD	2		/*CLK*/
#define MT48LC16M16A2_tXSR	67  /*ns*/
#define MT48LC16M16A2_tRAS	42  /*ns*/
#define MT48LC16M16A2_tRC		60  /*ns*/
#define MT48LC16M16A2_tWR		6		/*ns + 1 CLK*/
#define MT48LC16M16A2_tRP		18	/*ns*/
#define MT48LC16M16A2_tRCD	18	/*ns*/
#define MT48LC16M16A2_FMC_CAS_LATENCY		FMC_SDRAM_CAS_LATENCY_3 

#define MT48LC16M16A2_FMC_BANK					FMC_SDRAM_BANK2 /*FMC_SDRAM_BANK1*/
#define MT48LC16M16A2_FMC_CLOCK_PERIOD	FMC_SDRAM_CLOCK_PERIOD_2 /*FMC_SDRAM_CLOCK_PERIOD_3*/

#if (MT48LC16M16A2_FMC_CLOCK_PERIOD == FMC_SDRAM_CLOCK_PERIOD_2)
	#define MT48LC16M16A2_FMC_tCLK    (1000000000 / (SystemCoreClock / 2))
#elif (MT48LC16M16A2_FMC_CLOCK_PERIOD == FMC_SDRAM_CLOCK_PERIOD_3)
  #define MT48LC16M16A2_FMC_tCLK    (1000000000 / (SystemCoreClock / 3))
#endif

#define MT48LC16M16A2_tRFC_CLK	(((MT48LC16M16A2_tRFC * 1000000) / MT48LC16M16A2_ROWS_CNT) % MT48LC16M16A2_FMC_tCLK ? (((MT48LC16M16A2_tRFC * 1000000) / MT48LC16M16A2_ROWS_CNT) / MT48LC16M16A2_FMC_tCLK) + 1 : ((MT48LC16M16A2_tRFC * 1000000) / MT48LC16M16A2_ROWS_CNT) % MT48LC16M16A2_FMC_tCLK)
#define MT48LC16M16A2_tMRD_CLK	(MT48LC16M16A2_tMRD)
#define MT48LC16M16A2_tXSR_CLK	(MT48LC16M16A2_tXSR % MT48LC16M16A2_FMC_tCLK ? (MT48LC16M16A2_tXSR / MT48LC16M16A2_FMC_tCLK) + 1 : MT48LC16M16A2_tXSR / MT48LC16M16A2_FMC_tCLK)
#define MT48LC16M16A2_tRAS_CLK	(MT48LC16M16A2_tRAS % MT48LC16M16A2_FMC_tCLK ? (MT48LC16M16A2_tRAS / MT48LC16M16A2_FMC_tCLK) + 1 : MT48LC16M16A2_tRAS / MT48LC16M16A2_FMC_tCLK)
#define MT48LC16M16A2_tRC_CLK		(MT48LC16M16A2_tRC % MT48LC16M16A2_FMC_tCLK ? (MT48LC16M16A2_tRC / MT48LC16M16A2_FMC_tCLK) + 1 : MT48LC16M16A2_tRC / MT48LC16M16A2_FMC_tCLK)
#define MT48LC16M16A2_tWR_CLK		(MT48LC16M16A2_tWR % MT48LC16M16A2_FMC_tCLK ? (MT48LC16M16A2_tWR / MT48LC16M16A2_FMC_tCLK) + 2 : (MT48LC16M16A2_tWR / MT48LC16M16A2_FMC_tCLK) + 1)
#define MT48LC16M16A2_tRP_CLK		(MT48LC16M16A2_tRP % MT48LC16M16A2_FMC_tCLK ? (MT48LC16M16A2_tRP / MT48LC16M16A2_FMC_tCLK) + 1 : MT48LC16M16A2_tRP / MT48LC16M16A2_FMC_tCLK)
#define MT48LC16M16A2_tRCD_CLK	(MT48LC16M16A2_tRCD % MT48LC16M16A2_FMC_tCLK ? (MT48LC16M16A2_tRCD / MT48LC16M16A2_FMC_tCLK) + 1 : MT48LC16M16A2_tRCD / MT48LC16M16A2_FMC_tCLK)

#if (MT48LC16M16A2_FMC_BANK == FMC_SDRAM_BANK1)
	#define MT48LC16M16A2_ADDR    ((uint32_t)0xC0000000)
#elif (MT48LC16M16A2_FMC_BANK == FMC_SDRAM_BANK2)
  #define MT48LC16M16A2_ADDR    ((uint32_t)0xD0000000)
#endif
#define MT48LC16M16A2_SIZE		((uint32_t)0x02000000)

typedef struct {
	BSP_DEV;
	SDRAM_HandleTypeDef hsdram;
} MT48LC16M16A2_T;

int32_t MT48LC16M16A2_Init(MT48LC16M16A2_T *Dev);
int32_t MT48LC16M16A2_PatternTest(MT48LC16M16A2_T *Dev, uint16_t Pattern);
int32_t MT48LC16M16A2_RandomTest(MT48LC16M16A2_T *Dev);

#endif /* __MT48LC16M16A2_H */
