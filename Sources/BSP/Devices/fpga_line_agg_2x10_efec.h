#ifndef __FPGA_LINE_AGG_2X10_EFEC_H
#define __FPGA_LINE_AGG_2X10_EFEC_H

#include "stm32f4xx_hal.h"
#include "bsp_config.h"
#include "bsp_dev.h"
#ifdef BSP_CONFIG_USE_FREERTOS
#include "cmsis_os.h"
#endif

#define FPGA_LINE_AGG_2X10_EFEC_LINE_CNT				2

#define FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_TX_PLL_LOCK_MASK 				(1 << 0)
#define FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_RX_PLL_LOCK_MASK 				(1 << 1)
#define FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_TX_CLB_DONE_MASK 				(1 << 2)
#define FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_RX_LOS_MASK 						(1 << 3)
#define FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_LOOPBACK_SERIAL_MASK 		(1 << 4)
#define FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_LOOPBACK_POST_CDR_MASK	(1 << 5)
#define FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_LOOPBACK_PRE_CDR_MASK 	(1 << 6)
#define FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_LOOPBACK_MASK 					(FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_LOOPBACK_SERIAL_MASK | FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_LOOPBACK_POST_CDR_MASK | FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_LOOPBACK_PRE_CDR_MASK)
#define FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_PWR_DOWM_MASK 					(1 << 7)
#define FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_LOOPBACK_SET(Dev, LineIdx, __Loopback) \
	((LineIdx) >= FPGA_LINE_AGG_2X10_EFEC_LINE_CNT) ? \
	-1 : \
	((Dev)->Line[(LineIdx)].PMAStatus = ((Dev)->Line[(LineIdx)].PMAStatus & (~(FPGA_LINE_AGG_2X10_EFEC_LINE_PMASTATUS_LOOPBACK_MASK))) | (__Loopback), 0)


#define FPGA_LINE_AGG_2X10_EFEC_LINE_STATUS_LOF_MASK						(1 << 1)
#define FPGA_LINE_AGG_2X10_EFEC_LINE_STATUS_AIS_MASK						(1 << 3)

#define FPGA_LINE_AGG_2X10_EFEC_LINE_CTRL_FEC_DISABLED_MASK	(1 << 7)
#define FPGA_LINE_AGG_2X10_EFEC_LINE_CTRL_SET(Dev, LineIdx, __Ctrl)  \
	((LineIdx) >= FPGA_LINE_AGG_2X10_EFEC_LINE_CNT) ? \
	-1 : \
	((Dev)->Line[(LineIdx)].Ctrl = (__Ctrl))
	
typedef struct {
	uint8_t PMAStatus;
	uint8_t __PMAStatus;
	uint8_t Ctrl;
	uint8_t __Ctrl;
	uint8_t __Status;
} FPGA_LINE_AGG_2X10_EFEC_LINE_T;

typedef struct {
	BSP_DEV;
	const uint32_t BaseAddr;
	char SwVersion[16];
	float Temp;
	FPGA_LINE_AGG_2X10_EFEC_LINE_T Line[FPGA_LINE_AGG_2X10_EFEC_LINE_CNT];
} FPGA_LINE_AGG_2X10_EFEC_T;

int32_t FPGA_LINE_AGG_2X10_EFEC_Init(FPGA_LINE_AGG_2X10_EFEC_T *Dev);
int32_t FPGA_LINE_AGG_2X10_EFEC_Update(FPGA_LINE_AGG_2X10_EFEC_T *Dev);
void FPGA_LINE_AGG_2X10_EFEC_Deinit(FPGA_LINE_AGG_2X10_EFEC_T *Dev);

#endif /* __FPGA_LINE_AGG_2X10_EFEC_H */
