#ifndef __FPGA_LINE_AGG_2X10_BS_H
#define __FPGA_LINE_AGG_2X10_BS_H

#include "stm32f4xx_hal.h"
#include "bsp_config.h"
#include "bsp_dev.h"
#ifdef BSP_CONFIG_USE_FREERTOS
#include "cmsis_os.h"
#endif

#define FPGA_LINE_AGG_2X10_BS_IFACE_CNT				4
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU1_CNT	4
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU0_CNT	8
#define FPGA_LINE_AGG_2X10_BS_AGG_CNT					2

#define FPGA_LINE_AGG_2X10_BS_AGG_MODE_LOCKOUT						(1 << 7)
#define FPGA_LINE_AGG_2X10_BS_AGG_MODE_FORCED							(1 << 6)
#define FPGA_LINE_AGG_2X10_BS_AGG_MODE_MANUAL							(1 << 5)
#define FPGA_LINE_AGG_2X10_BS_AGG_MODE_AUTO_NON_REVERTIVE	0x00
#define FPGA_LINE_AGG_2X10_BS_AGG_MODE_AUTO_REVERTIVE 		(1 << 0)
#define FPGA_LINE_AGG_2X10_BS_AGG_MODE_SET(Dev, AGGIdx, AGGMode) \
	((AGGIdx) >= FPGA_LINE_AGG_2X10_BS_AGG_CNT) ? \
	-1 : \
	((Dev)->AGG[AGGIdx].Mode = (AGGMode), 0)
#define FPGA_LINE_AGG_2X10_BS_AGG_WTR_SET(Dev, AGGIdx, WTRTmr) 	\
	((AGGIdx) >= FPGA_LINE_AGG_2X10_BS_AGG_CNT) ? \
	-1 : \
	((Dev)->AGG[AGGIdx].WTR = (WTRTmr), 0)
#define FPGA_LINE_AGG_2X10_BS_AGG_HO_SET(Dev, AGGIdx, HOTmr) 		\
	((AGGIdx) >= FPGA_LINE_AGG_2X10_BS_AGG_CNT) ? \
	-1 : \
	((Dev)->AGG[AGGIdx].HO = (HOTmr), 0)

#define FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_TX_PLL_LOCK_MASK 				(1 << 0)
#define FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_RX_PLL_LOCK_MASK 				(1 << 1)
#define FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_TX_CLB_DONE_MASK 				(1 << 2)
#define FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_RX_LOS_MASK 						(1 << 3)
#define FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_LOOPBACK_SERIAL_MASK 		(1 << 4)
#define FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_LOOPBACK_POST_CDR_MASK	(1 << 5)
#define FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_LOOPBACK_PRE_CDR_MASK 	(1 << 6)
#define FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_LOOPBACK_MASK 					(FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_LOOPBACK_SERIAL_MASK | FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_LOOPBACK_POST_CDR_MASK | FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_LOOPBACK_PRE_CDR_MASK)
#define FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_PWR_DOWM_MASK 					(1 << 7)
#define FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_LOOPBACK_SET(Dev, IfaceIdx, __Loopback) \
	((IfaceIdx) >= FPGA_LINE_AGG_2X10_BS_IFACE_CNT) ? \
	-1 : \
	((Dev)->Iface[(IfaceIdx)].PMAStatus = ((Dev)->Iface[(IfaceIdx)].PMAStatus & (~(FPGA_LINE_AGG_2X10_BS_IFACE_PMASTATUS_LOOPBACK_MASK))) | (__Loopback), 0)


#define FPGA_LINE_AGG_2X10_BS_IFACE_OTU2_ALARMS_LOS_MASK					(1 << 0)
#define FPGA_LINE_AGG_2X10_BS_IFACE_OTU2_ALARMS_LOF_MASK					(1 << 1)
#define FPGA_LINE_AGG_2X10_BS_IFACE_OTU2_ALARMS_LOM_MASK					(1 << 2)
#define FPGA_LINE_AGG_2X10_BS_IFACE_OTU2_ALARMS_SMBIP8_MASK				(1 << 4)
#define FPGA_LINE_AGG_2X10_BS_IFACE_OTU2_ALARMS_FEC_CORR_MASK			(1 << 5)
#define FPGA_LINE_AGG_2X10_BS_IFACE_OTU2_ALARMS_FEC_UNCORR_MASK		(1 << 6)
#define FPGA_LINE_AGG_2X10_BS_IFACE_OTU2_ALARMS_FEC_DISABLED_MASK	(1 << 7)
#define FPGA_LINE_AGG_2X10_BS_IFACE_OTU2_ALARMS_SMBEI_MASK				(0x0F << 12)
#define FPGA_LINE_AGG_2X10_BS_IFACE_OTU2_ALARMS_SMBDI_MASK				(1 << 11)
#define FPGA_LINE_AGG_2X10_BS_IFACE_OTU2_ALARMS_SMIAE_MASK				(1 << 10)

#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_SD_MASK				(1 << 0)
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_LOF_MASK			(1 << 1)
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_LOM_MASK			(1 << 2)
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_AIS_MASK			(1 << 3)
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_PMBIP8_MASK		(1 << 4)
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_OPUCSF_MASK		(1 << 5)
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_PMBEI_MASK		(0x0F << 12)
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_PMBDI_MASK		(1 << 11)
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_STAT_MASK			(0x07 << 8)
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_STAT_OCI_MASK	(0x06 << 8)
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_STAT_LCK_MASK	(0x05 << 8)
#define FPGA_LINE_AGG_2X10_BS_IFACE_ODU2_ALARMS_STAT_AIS_MASK	(0x07 << 8)

#define FPGA_LINE_AGG_2X10_BS_IFACE_CTRL_CNTR_EN_MASK				(1 << 0)
#define FPGA_LINE_AGG_2X10_BS_IFACE_CTRL_CNTR_RST_MASK			(1 << 1)
#define FPGA_LINE_AGG_2X10_BS_IFACE_CTRL_FEC_DISABLED_MASK	(1 << 7)
#define FPGA_LINE_AGG_2X10_BS_IFACE_CTRL_SET(Dev, IfaceIdx, __Ctrl)  \
	((IfaceIdx) >= FPGA_LINE_AGG_2X10_BS_IFACE_CNT) ? \
	-1 : \
	((Dev)->Iface[(IfaceIdx)].Ctrl = (__Ctrl))
	
#define FPGA_LINE_AGG_2X10_BS_AGG_STATUS_SF_PRIMARY (1 << 0)
#define FPGA_LINE_AGG_2X10_BS_AGG_STATUS_SD_PRIMARY (1 << 1)
#define FPGA_LINE_AGG_2X10_BS_AGG_STATUS_MUX_VALUE	(1 << 3)
#define FPGA_LINE_AGG_2X10_BS_AGG_STATUS_SF_PROTECT (1 << 4)
#define FPGA_LINE_AGG_2X10_BS_AGG_STATUS_SD_PROTECT (1 << 5)

typedef struct {
	uint8_t __Mode;
	uint8_t Mode;
	uint8_t __Status;
	uint8_t WTR;
	uint8_t __WTR;
	uint8_t HO;
	uint8_t __HO;
} FPGA_LINE_AGG_2X10_BS_AGG_T;

typedef struct {
	uint8_t PMAStatus;
	uint8_t __PMAStatus;
	uint8_t Ctrl;
	uint8_t __Ctrl;
	uint16_t __OTU2Alarms;
	uint16_t OTU2BIP;
	uint16_t __OTU2BIP;
	uint32_t OTU2FECCorr;
	uint32_t __OTU2FECCorr;
	uint16_t OTU2FECUncorr;
	uint16_t __OTU2FECUncorr;
	uint16_t __ODU2Alarms;
	uint16_t ODU2BIP;
	uint16_t __ODU2BIP;
} FPGA_LINE_AGG_2X10_BS_IFACE_T;

typedef struct {
	BSP_DEV;
	const uint32_t BaseAddr;
	char SwVersion[16];
	float Temp;
	FPGA_LINE_AGG_2X10_BS_IFACE_T Iface[FPGA_LINE_AGG_2X10_BS_IFACE_CNT];
	FPGA_LINE_AGG_2X10_BS_AGG_T AGG[2];
} FPGA_LINE_AGG_2X10_BS_T;

int32_t FPGA_LINE_AGG_2X10_BS_Init(FPGA_LINE_AGG_2X10_BS_T *Dev);
int32_t FPGA_LINE_AGG_2X10_BS_Update(FPGA_LINE_AGG_2X10_BS_T *Dev);
void FPGA_LINE_AGG_2X10_BS_Deinit(FPGA_LINE_AGG_2X10_BS_T *Dev);

#endif /* __FPGA_LINE_AGG_2X10_BS_H */
