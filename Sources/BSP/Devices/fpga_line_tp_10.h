#ifndef __FPGA_LINE_TP_10_H
#define __FPGA_LINE_TP_10_H

#include "stm32f4xx_hal.h"
#include "bsp_config.h"
#include "bsp_dev.h"
#ifdef BSP_CONFIG_USE_FREERTOS
#include "cmsis_os.h"
#endif

#define FPGA_LINE_TP_10_LINE_CNT	2

#define FPGA_LINE_TP_10_LINE_PMASTATUS_TX_PLL_LOCK_MASK 			(1 << 0)
#define FPGA_LINE_TP_10_LINE_PMASTATUS_RX_PLL_LOCK_MASK 			(1 << 1)
#define FPGA_LINE_TP_10_LINE_PMASTATUS_TX_CLB_DONE_MASK 			(1 << 2)
#define FPGA_LINE_TP_10_LINE_PMASTATUS_RX_LOS_MASK 						(1 << 3)
#define FPGA_LINE_TP_10_LINE_PMASTATUS_LOOPBACK_SERIAL_MASK 	(1 << 4)
#define FPGA_LINE_TP_10_LINE_PMASTATUS_LOOPBACK_POST_CDR_MASK	(1 << 5)
#define FPGA_LINE_TP_10_LINE_PMASTATUS_LOOPBACK_PRE_CDR_MASK 	(1 << 6)
#define FPGA_LINE_TP_10_LINE_PMASTATUS_LOOPBACK_MASK 					(FPGA_LINE_TP_10_LINE_PMASTATUS_LOOPBACK_SERIAL_MASK | FPGA_LINE_TP_10_LINE_PMASTATUS_LOOPBACK_POST_CDR_MASK | FPGA_LINE_TP_10_LINE_PMASTATUS_LOOPBACK_PRE_CDR_MASK)
#define FPGA_LINE_TP_10_LINE_PMASTATUS_PWR_DOWM_MASK 					(1 << 7)
#define FPGA_LINE_TP_10_LINE_PMASTATUS_LOOPBACK_SET(Dev, LineIdx, __Loopback) \
	((LineIdx) >= FPGA_LINE_TP_10_LINE_CNT) ? \
	-1 : \
	((Dev)->Line[(LineIdx)].PMAStatus = ((Dev)->Line[(LineIdx)].PMAStatus & (~(FPGA_LINE_TP_10_LINE_PMASTATUS_LOOPBACK_MASK))) | (__Loopback), 0)


#define FPGA_LINE_TP_10_LINE_OTU2_ALARMS_LOS_MASK					(1 << 0)
#define FPGA_LINE_TP_10_LINE_OTU2_ALARMS_LOF_MASK					(1 << 1)
#define FPGA_LINE_TP_10_LINE_OTU2_ALARMS_LOM_MASK					(1 << 2)
#define FPGA_LINE_TP_10_LINE_OTU2_ALARMS_SMBIP8_MASK				(1 << 4)
#define FPGA_LINE_TP_10_LINE_OTU2_ALARMS_FEC_CORR_MASK			(1 << 5)
#define FPGA_LINE_TP_10_LINE_OTU2_ALARMS_FEC_UNCORR_MASK		(1 << 6)
#define FPGA_LINE_TP_10_LINE_OTU2_ALARMS_FEC_DISABLED_MASK	(1 << 7)
#define FPGA_LINE_TP_10_LINE_OTU2_ALARMS_SMBEI_MASK				(0x0F << 12)
#define FPGA_LINE_TP_10_LINE_OTU2_ALARMS_SMBDI_MASK				(1 << 11)
#define FPGA_LINE_TP_10_LINE_OTU2_ALARMS_SMIAE_MASK				(1 << 10)

#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_SD_MASK				(1 << 0)
#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_LOF_MASK			(1 << 1)
#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_LOM_MASK			(1 << 2)
#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_AIS_MASK			(1 << 3)
#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_PMBIP8_MASK		(1 << 4)
#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_OPUCSF_MASK		(1 << 5)
#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_PMBEI_MASK		(0x0F << 12)
#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_PMBDI_MASK		(1 << 11)
#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_STAT_MASK			(0x07 << 8)
#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_STAT_OCI_MASK	(0x06 << 8)
#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_STAT_LCK_MASK	(0x05 << 8)
#define FPGA_LINE_TP_10_LINE_ODU2_ALARMS_STAT_AIS_MASK	(0x07 << 8)

#define FPGA_LINE_TP_10_LINE_CTRL_CNTR_EN_MASK				(1 << 0)
#define FPGA_LINE_TP_10_LINE_CTRL_CNTR_RST_MASK			(1 << 1)
#define FPGA_LINE_TP_10_LINE_CTRL_FEC_DISABLED_MASK	(1 << 7)
#define FPGA_LINE_TP_10_LINE_CTRL_SET(Dev, LineIdx, __Ctrl)  \
	((LineIdx) >= FPGA_LINE_TP_10_LINE_CNT) ? \
	-1 : \
	((Dev)->Line[(LineIdx)].Ctrl = (__Ctrl))

#define FPGA_LINE_TP_10_CLIENT_CNT	2

#define FPGA_LINE_TP_10_CLIENT_MODE_10GE	0
#define FPGA_LINE_TP_10_CLIENT_MODE_STM64	1
#define FPGA_LINE_TP_10_CLIENT_MODE_SET(Dev, ClientIdx, __Mode)  \
	((ClientIdx) >= FPGA_LINE_TP_10_CLIENT_CNT) ? \
	-1 : \
	((Dev)->Client[(ClientIdx)].Mode = (__Mode))

#define FPGA_LINE_TP_10_CLIENT_PMASTATUS_TX_PLL_LOCK_MASK 			(1 << 0)
#define FPGA_LINE_TP_10_CLIENT_PMASTATUS_RX_PLL_LOCK_MASK 			(1 << 1)
#define FPGA_LINE_TP_10_CLIENT_PMASTATUS_TX_CLB_DONE_MASK 			(1 << 2)
#define FPGA_LINE_TP_10_CLIENT_PMASTATUS_RX_LOS_MASK 						(1 << 3)
#define FPGA_LINE_TP_10_CLIENT_PMASTATUS_LOOPBACK_SERIAL_MASK 	(1 << 4)
#define FPGA_LINE_TP_10_CLIENT_PMASTATUS_LOOPBACK_POST_CDR_MASK	(1 << 5)
#define FPGA_LINE_TP_10_CLIENT_PMASTATUS_LOOPBACK_PRE_CDR_MASK 	(1 << 6)
#define FPGA_LINE_TP_10_CLIENT_PMASTATUS_LOOPBACK_MASK 					(FPGA_LINE_TP_10_CLIENT_PMASTATUS_LOOPBACK_SERIAL_MASK | FPGA_LINE_TP_10_CLIENT_PMASTATUS_LOOPBACK_POST_CDR_MASK | FPGA_LINE_TP_10_CLIENT_PMASTATUS_LOOPBACK_PRE_CDR_MASK)
#define FPGA_LINE_TP_10_CLIENT_PMASTATUS_PWR_DOWM_MASK 					(1 << 7)
#define FPGA_LINE_TP_10_CLIENT_PMASTATUS_LOOPBACK_SET(Dev, ClientIdx, __Loopback) \
	((ClientIdx) >= FPGA_LINE_TP_10_CLIENT_CNT) ? \
	-1 : \
	((Dev)->Client[(ClientIdx)].PMAStatus = ((Dev)->Client[(ClientIdx)].PMAStatus & (~(FPGA_LINE_TP_10_CLIENT_PMASTATUS_LOOPBACK_MASK))) | (__Loopback), 0)

#define FPGA_LINE_TP_10_CLIENT_SDH_RX_STATUS_LOF_MASK 		(1 << 0)
#define FPGA_LINE_TP_10_CLIENT_SDH_RX_STATUS_AIS_MASK 		(1 << 3)
#define FPGA_LINE_TP_10_CLIENT_SDH_RX_STATUS_MSRDI_MASK 	(1 << 4)
#define FPGA_LINE_TP_10_CLIENT_SDH_RX_STATUS_MSREI_MASK 	(1 << 5)
#define FPGA_LINE_TP_10_CLIENT_SDH_RX_STATUS_BIP8_MASK 		(1 << 6)
#define FPGA_LINE_TP_10_CLIENT_SDH_RX_STATUS_BIP24_MASK 	(1 << 7)

typedef struct {
	uint32_t RxPkts;
	uint32_t RxOcts;
	uint16_t RxErrs;
	uint32_t TxPkts;
	uint32_t TxOcts;
	uint16_t TxErrs;
	uint32_t __RxPkts;
	uint32_t __RxOcts;
	uint16_t __RxErrs;
	uint32_t __TxPkts;
	uint32_t __TxOcts;
	uint16_t __TxErrs;
} FPGA_LINE_TP_10_CLIENT_ETH_T;

typedef struct {
	uint8_t __RxStatus;
	uint16_t BIP8;
	uint16_t __BIP8;
	uint16_t BIP24;
	uint16_t __BIP24;
} FPGA_LINE_TP_10_CLIENT_SDH_T;

typedef struct {
	uint8_t Mode;
	uint8_t __Mode;
	uint8_t PMAStatus;
	uint8_t __PMAStatus;
	uint8_t __PCSStatus;
	uint8_t Ctrl;
	uint8_t __Ctrl;
	FPGA_LINE_TP_10_CLIENT_SDH_T SDH;
	FPGA_LINE_TP_10_CLIENT_ETH_T Eth;
} FPGA_LINE_TP_10_CLIENT_T;

typedef struct {
	uint16_t __Alarms;
	uint16_t BIP;
	uint16_t __BIP;
	uint32_t FECCorr;
	uint32_t __FECCorr;
	uint16_t FECUncorr;
	uint16_t __FECUncorr;
} FPGA_LINE_TP_10_LINE_OTU2_T;

typedef struct {
	uint16_t __Alarms;
	uint16_t BIP;
	uint16_t __BIP;
} FPGA_LINE_TP_10_LINE_ODU2_T;

typedef struct {
	uint8_t PMAStatus;
	uint8_t __PMAStatus;
	uint8_t Ctrl;
	uint8_t __Ctrl;
	FPGA_LINE_TP_10_LINE_OTU2_T OTU2;
	FPGA_LINE_TP_10_LINE_ODU2_T ODU2;
} FPGA_LINE_TP_10_LINE_T;

typedef struct {
	BSP_DEV;
	const uint32_t BaseAddr;
	char SwVersion[16];
	float Temp;
	FPGA_LINE_TP_10_LINE_T Line[FPGA_LINE_TP_10_LINE_CNT];
	FPGA_LINE_TP_10_CLIENT_T Client[FPGA_LINE_TP_10_CLIENT_CNT];
} FPGA_LINE_TP_10_T;

int32_t FPGA_LINE_TP_10_Init(FPGA_LINE_TP_10_T *Dev);
int32_t FPGA_LINE_TP_10_Update(FPGA_LINE_TP_10_T *Dev);
void FPGA_LINE_TP_10_Deinit(FPGA_LINE_TP_10_T *Dev);

#endif /* __FPGA_LINE_TP_10_H */
