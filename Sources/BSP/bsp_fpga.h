#define BSP_FPGA_CLIENT_CNT	2

#define BSP_FPGA_MAXV_ADDR	0x68006000
#define BSP_FPGA_LINE_ADDR	0x68000000
#define BSP_FPGA_CLIENT_ADDR(Idx)	(0x68002000 + ((Idx) * 0x2000))

#define BSP_FPGA_MAXV_LINE_STATUS_MASK				(1 << 1)
#define BSP_FPGA_MAXV_CLIENT_STATUS_MASK(Idx)	(1 << ((Idx) + 2))

#define BSP_FPGA_LINE_IFACE_CNT	4
#define BSP_FPGA_LINE_IFACE_ODU1_CNT	4
#define BSP_FPGA_LINE_IFACE_ODU0_CNT	8
#define BSP_FPGA_LINE_CMD_ADDR				(BSP_FPGA_LINE_ADDR + 0x08)
#define BSP_FPGA_LINE_CMD_OPT1_ADDR		(BSP_FPGA_LINE_ADDR + 0x09)
#define BSP_FPGA_LINE_CMD_OPT2_ADDR		(BSP_FPGA_LINE_ADDR + 0x0A)
#define BSP_FPGA_LINE_CMD_OPT3_ADDR		(BSP_FPGA_LINE_ADDR + 0x0B)
#define BSP_FPGA_LINE_STATUS_ADDR			(BSP_FPGA_LINE_ADDR + 0x0C)
#define BSP_FPGA_LINE_STATUS_OPT_ADDR	(BSP_FPGA_CLIENT_ADDR(DevIdx) + 0x0D)
#define BSP_FPGA_LINE_IFACE_ADDR(IfaceIdx)   (BSP_FPGA_LINE_ADDR + ((IfaceIdx) * 0x100) + 0x100)

#define BSP_FPGA_LINE_IFACE_OTU2_ALARM_LOS_MASK	(1 << 0)
#define BSP_FPGA_LINE_IFACE_OTU2_ALARM_LOF_MASK	(1 << 1)
#define BSP_FPGA_LINE_IFACE_OTU2_ALARM_LOM_MASK	(1 << 2)
#define BSP_FPGA_LINE_IFACE_OTU2_ALARM_SMBIP8_MASK	(1 << 4)
#define BSP_FPGA_LINE_IFACE_OTU2_ALARM_SMBEI_MASK	(0x0F << 12)
#define BSP_FPGA_LINE_IFACE_OTU2_ALARM_SMBDI_MASK	(1 << 11)
#define BSP_FPGA_LINE_IFACE_OTU2_ALARM_SMIAE_MASK	(1 << 10)

#define BSP_FPGA_LINE_IFACE_ODU2_ALARM_LOF_MASK	(1 << 1)
#define BSP_FPGA_LINE_IFACE_ODU2_ALARM_LOM_MASK	(1 << 2)
#define BSP_FPGA_LINE_IFACE_ODU2_ALARM_AIS_MASK	(1 << 3)
#define BSP_FPGA_LINE_IFACE_ODU2_ALARM_PMBIP8_MASK	(1 << 4)
#define BSP_FPGA_LINE_IFACE_ODU2_ALARM_OPUCSF_MASK	(1 << 5)
#define BSP_FPGA_LINE_IFACE_ODU2_ALARM_PMBEI_MASK	(0x0F << 12)
#define BSP_FPGA_LINE_IFACE_ODU2_ALARM_PMBDI_MASK	(1 << 11)

#define BSP_FPGA_LINE_IFACE_PMASTATUS_TX_PLL_LOCK_MASK 				(1 << 0)
#define BSP_FPGA_LINE_IFACE_PMASTATUS_RX_PLL_LOCK_MASK 				(1 << 1)
#define BSP_FPGA_LINE_IFACE_PMASTATUS_TX_CLB_DONE_MASK 				(1 << 2)
#define BSP_FPGA_LINE_IFACE_PMASTATUS_RX_LOS_MASK 						(1 << 3)
#define BSP_FPGA_LINE_IFACE_PMASTATUS_LOOPBACK_SERIAL_MASK 		(1 << 4)
#define BSP_FPGA_LINE_IFACE_PMASTATUS_LOOPBACK_POST_CDR_MASK 	(1 << 5)
#define BSP_FPGA_LINE_IFACE_PMASTATUS_LOOPBACK_PRE_CDR_MASK 	(1 << 6)
#define BSP_FPGA_LINE_IFACE_PMASTATUS_PWR_DOWM_MASK 					(1 << 7)

#define BSP_FPGA_LINE_IFACE_IDX(LineIdx)	(LineIdx)

#define BSP_FPGA_LINE_MUX_OPU0_CNT	16
#define BSP_FPGA_LINE_MUX_OPU0_PAYLOAD_TYPE_ADDR(OPU0Idx)   (BSP_FPGA_LINE_ADDR + 0x530 + (OPU0Idx))

#define BSP_FPGA_LINE_MUX_OPU0_PAYLOAD_TYPE_STM1	0x0A
#define BSP_FPGA_LINE_MUX_OPU0_PAYLOAD_TYPE_STM4	0x0B
#define BSP_FPGA_LINE_MUX_OPU0_PAYLOAD_TYPE_1GE		0x07

#define BSP_FPGA_LINE_MUX_OPU0_PAYLOAD_TYPE_SET(OPU0Idx, PayloadType) ((OPU0Idx) >= BSP_FPGA_LINE_MUX_OPU0_CNT) ? -1: ((fpga_line.Mux.OPU0PayloadType[OPU0Idx] = (PayloadType)), 0)

#define BSP_FPGA_LINE_MUX_OPU1_CNT	8
#define BSP_FPGA_LINE_MUX_OPU1_PAYLOAD_TYPE_ADDR(OPU1Idx)   (BSP_FPGA_LINE_ADDR + 0x518 + (OPU1Idx))

#define BSP_FPGA_LINE_MUX_OPU1_PAYLOAD_TYPE_2xODU0	0x20
#define BSP_FPGA_LINE_MUX_OPU1_PAYLOAD_TYPE_STM16		0x02

#define BSP_FPGA_LINE_MUX_OPU1_PAYLOAD_TYPE_SET(OPU1Idx, PayloadType) ((OPU1Idx) >= BSP_FPGA_LINE_MUX_OPU1_CNT) ? -1: ((fpga_line.Mux.OPU1PayloadType[OPU1Idx] = (PayloadType)), 0)

#define BSP_FPGA_LINE_MUX_CLIENT_CNT	16
#define BSP_FPGA_LINE_MUX_CLIENT_ADDR(ODU01Idx)   (BSP_FPGA_LINE_ADDR + 0x500 + (ODU01Idx))

#define BSP_FPGA_LINE_MUX_CLIENT_LINE_ODU0_SET(ClientIdx, LineIdx, ODU0Idx) (((ClientIdx) >= BSP_FPGA_LINE_MUX_CLIENT_CNT) ? -1: (((LineIdx) >= 2) ? -1 : ((ODU0Idx >= 8) ? -1 : ((fpga_line.Mux.Client[ClientIdx] = ((LineIdx) * 8) + (ODU0Idx) + 0x10) , 0))))
#define BSP_FPGA_LINE_MUX_CLIENT_LINE_ODU1_SET(ClientIdx, LineIdx, ODU1Idx) (((ClientIdx) >= BSP_FPGA_LINE_MUX_CLIENT_CNT) ? -1: (((LineIdx) >= 2) ? -1 : ((ODU1Idx >= 8) ? -1 : ((fpga_line.Mux.Client[ClientIdx] = ((LineIdx) * 4) + (ODU1Idx) + 0x00) , 0))))


#define BSP_FPGA_LINE_MUX_ODU01_CNT	16
#define BSP_FPGA_LINE_MUX_ODU01_ADDR(ODU01Idx)   (BSP_FPGA_LINE_ADDR + 0x520 + (ODU01Idx))

#define BSP_FPGA_LINE_MUX_ODU01_LINE(LineIdx, ODU0Idx)	(((LineIdx) >= 2) ? -1 : ((ODU0Idx >= 8) ? -1 : ((((LineIdx) * 8) + (ODU0Idx)) , 0)))
#define BSP_FPGA_LINE_MUX_ODU01_CLIENT(ClientIdx)				(((ClientIdx) >= 16) ? -1 : ((ClientIdx) + 0x10))

#define BSP_FPGA_LINE_MUX_ODU01_SET(ODU01Idx, Source) ((ODU01Idx) >= BSP_FPGA_LINE_MUX_ODU01_CNT) ? -1: ((fpga_line.Mux.ODU01[ODU01Idx] = (Source)), 0)

#define BSP_FPGA_LINE_MUX_ODU12_CNT	8
#define BSP_FPGA_LINE_MUX_ODU12_ADDR(ODU12Idx)   (BSP_FPGA_LINE_ADDR + 0x510 + (ODU12Idx))

#define BSP_FPGA_LINE_MUX_ODU12_LINE(LineIdx, ODU1Idx)	(((LineIdx) >= 2) ? -1 : ((ODU1Idx >= 4) ? -1 : ((((LineIdx) * 4) + (ODU1Idx)) , 0)))
#define BSP_FPGA_LINE_MUX_ODU12_ODU1(ODU1Idx)						(((ODU1Idx) >= 8) ? -1 : ((ODU1Idx) + 0x08))

#define BSP_FPGA_LINE_MUX_ODU12_SET(ODU12Idx, Source) 	((ODU12Idx) >= BSP_FPGA_LINE_MUX_ODU12_CNT) ? -1: ((fpga_line.Mux.ODU1[ODU12Idx] = (Source)), 0)

#define BSP_FPGA_LINE_LOOPBACK_NO 			0
#define BSP_FPGA_LINE_LOOPBACK_SERIAL 	1
#define BSP_FPGA_LINE_LOOPBACK_POST_CDR	2
#define BSP_FPGA_LINE_LOOPBACK_PRE_CDR	3

#define BSP_FPGA_LINE_IFACE_PMASTATUS_LOOPBACK_MASK 		(BSP_FPGA_LINE_IFACE_PMASTATUS_LOOPBACK_SERIAL_MASK | BSP_FPGA_LINE_IFACE_PMASTATUS_LOOPBACK_POST_CDR_MASK | BSP_FPGA_LINE_IFACE_PMASTATUS_LOOPBACK_PRE_CDR_MASK)

#define BSP_FPGA_LINE_LOOPBACK_SET(LineIdx, LineLoopback) \
do { \
	fpga_line.Iface[BSP_FPGA_LINE_IFACE_IDX(LineIdx)].PMAStatus &= ~(BSP_FPGA_LINE_IFACE_PMASTATUS_LOOPBACK_MASK); \
	if (LineLoopback == BSP_FPGA_LINE_LOOPBACK_SERIAL) \
		fpga_line.Iface[BSP_FPGA_LINE_IFACE_IDX(LineIdx)].PMAStatus |= BSP_FPGA_LINE_IFACE_PMASTATUS_LOOPBACK_SERIAL_MASK; \
	else if (LineLoopback == BSP_FPGA_LINE_LOOPBACK_POST_CDR) \
		fpga_line.Iface[BSP_FPGA_LINE_IFACE_IDX(LineIdx)].PMAStatus |= BSP_FPGA_LINE_IFACE_PMASTATUS_LOOPBACK_POST_CDR_MASK; \
	else if (LineLoopback == BSP_FPGA_LINE_LOOPBACK_PRE_CDR) \
		fpga_line.Iface[BSP_FPGA_LINE_IFACE_IDX(LineIdx)].PMAStatus |= BSP_FPGA_LINE_IFACE_PMASTATUS_LOOPBACK_PRE_CDR_MASK; \
} while(0) 

#define BSP_FPGA_CLIENT_IFACE_CNT	8
#define BSP_FPGA_CLIENT_CMD_ADDR(DevIdx)				(BSP_FPGA_CLIENT_ADDR(DevIdx) + 0x08)
#define BSP_FPGA_CLIENT_CMD_OPT1_ADDR(DevIdx)		(BSP_FPGA_CLIENT_ADDR(DevIdx) + 0x09)
#define BSP_FPGA_CLIENT_CMD_OPT2_ADDR(DevIdx)		(BSP_FPGA_CLIENT_ADDR(DevIdx) + 0x0A)
