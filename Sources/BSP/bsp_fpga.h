#define BSP_FPGA_CLIENT_LOOPBACK_SET(ClientIdx, ClientLoopback) \
do { \
	fpga_client[BSP_FPGA_CLIENT_FPGA_IDX(ClientIdx)].Iface[BSP_FPGA_CLIENT_IFACE_IDX(ClientIdx)].PMAStatus &= ~(BSP_FPGA_CLIENT_IFACE_PMASTATUS_LOOPBACK_MASK); \
	if (ClientLoopback == BSP_FPGA_CLIENT_LOOPBACK_SERIAL) \
		fpga_client[BSP_FPGA_CLIENT_FPGA_IDX(ClientIdx)].Iface[BSP_FPGA_CLIENT_IFACE_IDX(ClientIdx)].PMAStatus |= BSP_FPGA_CLIENT_IFACE_PMASTATUS_LOOPBACK_SERIAL_MASK; \
	else if (ClientLoopback == BSP_FPGA_CLIENT_LOOPBACK_POST_CDR) \
		fpga_client[BSP_FPGA_CLIENT_FPGA_IDX(ClientIdx)].Iface[BSP_FPGA_CLIENT_IFACE_IDX(ClientIdx)].PMAStatus |= BSP_FPGA_CLIENT_IFACE_PMASTATUS_LOOPBACK_POST_CDR_MASK; \
	else if (ClientLoopback == BSP_FPGA_CLIENT_LOOPBACK_PRE_CDR) \
		fpga_client[BSP_FPGA_CLIENT_FPGA_IDX(ClientIdx)].Iface[BSP_FPGA_CLIENT_IFACE_IDX(ClientIdx)].PMAStatus |= BSP_FPGA_CLIENT_IFACE_PMASTATUS_LOOPBACK_PRE_CDR_MASK; \
} while(0)

