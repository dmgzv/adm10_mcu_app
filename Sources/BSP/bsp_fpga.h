#define BSP_FPGA_CLIENT_MODE_SET(ClientIdx, ClientMode)	fpga_client[BSP_FPGA_CLIENT_FPGA_IDX(ClientIdx)].Iface[BSP_FPGA_CLIENT_IFACE_IDX(ClientIdx)].Mode = (ClientMode)
#define BSP_FPGA_CLIENT_MODE_GET(ClientIdx, ClientMode)	fpga_client[BSP_FPGA_CLIENT_FPGA_IDX(ClientIdx)].Iface[BSP_FPGA_CLIENT_IFACE_IDX(ClientIdx)].Mode

