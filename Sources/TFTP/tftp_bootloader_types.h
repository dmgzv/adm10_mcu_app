#ifndef TFTP_BOOTLOADER_TYPES_H
#define TFTP_BOOTLOADER_TYPES_H

#include <stdint.h>
#include "cmsis_os.h"

#define TFTP_BOOTLOADER_STATUS_IDLE					0
#define TFTP_BOOTLOADER_STATUS_IN_PROGRESS	1
#define TFTP_BOOTLOADER_STATUS_ERROR				2
#define TFTP_BOOTLOADER_STATUS_COMPLETE			3

#define TFTP_BOOTLOADER_FILE_STATUS_IDLE										0x00
#define TFTP_BOOTLOADER_FILE_STATUS_IDLE_COMPLETE						0x01
#define TFTP_BOOTLOADER_FILE_STATUS_IDLE_TIMEOUT						0x02
#define TFTP_BOOTLOADER_FILE_STATUS_IDLE_ERROR							0x03
#define TFTP_BOOTLOADER_FILE_STATUS_DOWNLOAD								0x10
#define TFTP_BOOTLOADER_FILE_STATUS_DOWNLOAD_COMPLETE				0x11
#define TFTP_BOOTLOADER_FILE_STATUS_DOWNLOAD_TIMEOUT				0x12
#define TFTP_BOOTLOADER_FILE_STATUS_DOWNLOAD_ERROR					0x13
#define TFTP_BOOTLOADER_FILE_STATUS_VERIFY									0x20
#define TFTP_BOOTLOADER_FILE_STATUS_VERIFY_COMPLETE					0x21
#define TFTP_BOOTLOADER_FILE_STATUS_VERIFY_TIMEOUT					0x22
#define TFTP_BOOTLOADER_FILE_STATUS_VERIFY_ERROR						0x23

#define TFTP_BOOTLOADER_COMPONENT_MSG(Dev, Msg)								((Dev)->MessageBase + (Msg))
/* This events are sent to component for internal processing*/
#define TFTP_BOOTLOADER_COMPONENT_MSG_IDLE(Dev)			 					TFTP_BOOTLOADER_COMPONENT_MSG((Dev), 0x000)
#define TFTP_BOOTLOADER_COMPONENT_MSG_DOWNLOAD(Dev)			 			TFTP_BOOTLOADER_COMPONENT_MSG((Dev), 0x100)
#define TFTP_BOOTLOADER_COMPONENT_MSG_UPDATE(Dev)							TFTP_BOOTLOADER_COMPONENT_MSG((Dev), 0x200)
/* This events are sent by component for external processing*/
#define TFTP_BOOTLOADER_COMPONENT_MSG_IDLE_COMPLETE(Dev)			TFTP_BOOTLOADER_COMPONENT_MSG((Dev), 0x0FE)
#define TFTP_BOOTLOADER_COMPONENT_MSG_IDLE_ERROR(Dev)					TFTP_BOOTLOADER_COMPONENT_MSG((Dev), 0x0FF)
#define TFTP_BOOTLOADER_COMPONENT_MSG_DOWNLOAD_COMPLETE(Dev)	TFTP_BOOTLOADER_COMPONENT_MSG((Dev), 0x1FE)
#define TFTP_BOOTLOADER_COMPONENT_MSG_DOWNLOAD_ERROR(Dev)			TFTP_BOOTLOADER_COMPONENT_MSG((Dev), 0x1FF)
#define TFTP_BOOTLOADER_COMPONENT_MSG_UPDATE_COMPLETE(Dev)		TFTP_BOOTLOADER_COMPONENT_MSG((Dev), 0x2FF)

typedef struct {
	uint32_t Status;
	char Name[128];
	uint32_t Size;
	char *Data;
	uint32_t MaxSize;
} TFTP_BOOTLOADER_FILE_T;

typedef struct {
	uint32_t Status;
	char *Addr;
	char *Dir;
	char Version[64];
	osMessageQId MessageQId;
	uint32_t MessageBase;
	TFTP_BOOTLOADER_FILE_T *Files;
	uint32_t FilesCnt;
	void (*ProcessEvent)(uint32_t Event);
	int32_t (*VerifyInfo)(char *Data);
} TFTP_BOOTLOADER_COMPONENT_T;

typedef struct {
	uint32_t Status;
	char Dir[64];
	char Addr[4];
	char Version[64];
	osMessageQId MessageQId;
	osThreadId ThreadId;
	osMutexId MutexId;
	TFTP_BOOTLOADER_FILE_T Info;
	TFTP_BOOTLOADER_COMPONENT_T **Components;
	uint32_t ComponentsCnt;
} TFTP_BOOTLOADER_T;

#endif /*TFTP_BOOTLOADER_TYPES_H*/
