#ifndef __PROFILE_FLASH_H
#define __PROFILE_FLASH_H

/* Includes ------------------------------------------------------------------*/
#include "profile_types.h"
#include "bsp_flash.h"

#define PROFILE_FLASH_HEADERS_START		( BSP_FLASH_PROFILE_HEADERS_ADDR_START )
#define	PROFILE_FLASH_HEADERS_SIZE		(	BSP_FLASH_PROFILE_HEADERS_ADDR_END - BSP_FLASH_PROFILE_HEADERS_ADDR_START )
#define PROFILE_FLASH_HEADERS_END			( BSP_FLASH_PROFILE_HEADERS_ADDR_END )

#define PROFILE_FLASH_CONFIGS_CNT			( BSP_CONFIG_PROFILES_CNT )
#define PROFILE_FLASH_CONFIGS_START		( BSP_FLASH_PROFILE_CONFIGS_ADDR_START )
#define	PROFILE_FLASH_CONFIGS_SIZE		(	BSP_FLASH_PROFILE_CONFIGS_ADDR_END - BSP_FLASH_PROFILE_CONFIGS_ADDR_START )
#define PROFILE_FLASH_CONFIGS_END			( BSP_FLASH_PROFILE_CONFIGS_ADDR_END )

#define	PROFILE_FLASH_CONFIG_SIZE				(	PROFILE_FLASH_CONFIGS_SIZE / PROFILE_FLASH_CONFIGS_CNT )
#define PROFILE_FLASH_CONFIG_START(Idx)	( PROFILE_FLASH_CONFIGS_START +  ((Idx) * PROFILE_FLASH_CONFIG_SIZE) )
#define PROFILE_FLASH_CONFIG_END(Idx)		( PROFILE_FLASH_CONFIG_START(Idx) +  PROFILE_FLASH_CONFIG_SIZE )

#define PROFILE_FLASH_LANGS_START 	( BSP_FLASH_PROFILE_LANGPACKS_ADDR_START )
#define PROFILE_FLASH_LANGS_SIZE 		( BSP_FLASH_PROFILE_LANGPACKS_ADDR_END - BSP_FLASH_PROFILE_LANGPACKS_ADDR_START)
#define PROFILE_FLASH_LANGS_END			( BSP_FLASH_PROFILE_LANGPACKS_ADDR_END )

#define	PROFILE_FLASH_LANG_SIZE				(	PROFILE_FLASH_LANGS_SIZE / BSP_CONFIG_PROFILES_CNT )
#define PROFILE_FLASH_LANG_START(Idx)	( PROFILE_FLASH_LANGS_START +  ((Idx) * PROFILE_FLASH_LANG_SIZE) )
#define PROFILE_FLASH_LANG_END(Idx)		( PROFILE_FLASH_LANG_START(Idx) +  PROFILE_FLASH_LANG_SIZE )

#define PROFILE_FLASH_LANG_BUFFER_SIZE (256)
	
typedef struct {
	BSP_FLASH_T *Flash;
	void *Values;
	uint32_t ValuesSize;
	osMutexId ValuesMutex;
	
	osThreadId ThreadId;
	osMessageQId MessageQId;
	
	uint32_t HeaderIdx;
	uint32_t ConfigIdx;
	uint32_t ProfileIdx;
	uint32_t EnableSave;
} PROFILE_FLASH_T;

int32_t PROFILE_FLASH_Init(PROFILE_FLASH_T *ProfileFlash, char *Name, BSP_FLASH_T *FlashInstance, void *Values, uint32_t ValuesSize, osMutexId ValuesMutex);

int32_t PROFILE_FLASH_ProfileIdxLoad(PROFILE_FLASH_T *ProfileFlash, uint32_t *ProfileIdx);
int32_t PROFILE_FLASH_ProfileIdxSave(PROFILE_FLASH_T *ProfileFlash, uint32_t ProfileIdx);

void PROFILE_FLASH_ParamsSave(PROFILE_FLASH_T *ProfileFlash);
int32_t PROFILE_FLASH_ParamsLoad(PROFILE_FLASH_T *ProfileFlash);

int32_t PROFILE_FLASH_LangpackSave(PROFILE_FLASH_T *ProfileFlash, char *Block, uint32_t Index);
int32_t PROFILE_FLASH_LangpackLoad(PROFILE_FLASH_T *ProfileFlash, char *Block, uint32_t Index);
int32_t PROFILE_FLASH_LangpackClear(PROFILE_FLASH_T *ProfileFlash);

#endif /* __PROFILE_FLASH_H */
