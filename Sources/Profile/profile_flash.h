#ifndef __PROFILE_FLASH_H
#define __PROFILE_FLASH_H

/* Includes ------------------------------------------------------------------*/
#include "profile_types.h"
#include "bsp_flash.h"

#define PROFILE_FLASH_HEADERS_START		( BSP_FLASH_CFG_ADDR )
#define	PROFILE_FLASH_HEADERS_SIZE		(	2 * BSP_FLASH_PAGE_SIZE )
#define PROFILE_FLASH_HEADERS_END			( PROFILE_FLASH_HEADERS_START + PROFILE_FLASH_HEADERS_SIZE )

#define PROFILE_FLASH_CONFIGS_CNT			( BSP_CONFIG_PROFILES_CNT )
#define PROFILE_FLASH_CONFIGS_START		( PROFILE_FLASH_HEADERS_END )
#define	PROFILE_FLASH_CONFIGS_SIZE		(	BSP_FLASH_CFG_SIZE - PROFILE_FLASH_HEADERS_SIZE )
#define PROFILE_FLASH_CONFIGS_END			( PROFILE_FLASH_CONFIGS_START + PROFILE_FLASH_CONFIGS_SIZE )

#define	PROFILE_FLASH_CONFIG_SIZE				(	PROFILE_FLASH_CONFIGS_SIZE / PROFILE_FLASH_CONFIGS_CNT )
#define PROFILE_FLASH_CONFIG_START(Idx)	( PROFILE_FLASH_CONFIGS_START +  ((Idx) * PROFILE_FLASH_CONFIG_SIZE) )
#define PROFILE_FLASH_CONFIG_END(Idx)		( PROFILE_FLASH_CONFIG_START(Idx) +  PROFILE_FLASH_CONFIG_SIZE )

#define PROFILE_FLASH_PROG_START 	( BSP_FLASH_FW_ADDR )
#define PROFILE_FLASH_PROG_SIZE		(	BSP_FLASH_FW_SIZE )
#define PROFILE_FLASH_PROG_END 		( PROFILE_FLASH_PROG_START + PROFILE_FLASH_PROG_SIZE )

#define PROFILE_FLASH_LANGS_START 	( BSP_FLASH_LANG_ADDR )
#define PROFILE_FLASH_LANGS_SIZE 		( BSP_FLASH_LANG_SIZE )
#define PROFILE_FLASH_LANGS_END			( PROFILE_FLASH_LANGS_START + PROFILE_FLASH_LANGS_SIZE )

#define	PROFILE_FLASH_LANG_SIZE				(	PROFILE_FLASH_LANGS_SIZE / BSP_CONFIG_PROFILES_CNT )
#define PROFILE_FLASH_LANG_START(Idx)	( PROFILE_FLASH_LANGS_START +  ((Idx) * PROFILE_FLASH_LANG_SIZE) )
#define PROFILE_FLASH_LANG_END(Idx)		( PROFILE_FLASH_LANG_START(Idx) +  PROFILE_FLASH_LANG_SIZE )

#if (PROFILE_FLASH_LANGS_END > BSP_FLASH_SIZE)
	#error Flash Size is too small for Profile
#endif
	
typedef struct {
	void *Values;
	uint32_t ValuesSize;
	osMutexId ValuesMutex;
	
	osThreadId ThreadId;
	osMessageQId MessageQId;
	
	uint32_t HeaderIdx;
	uint32_t ConfigIdx;
	uint32_t ProfileIdx;
	uint32_t EnableSave;
} PROFILE_FLASH_T;

int32_t PROFILE_FLASH_Init(PROFILE_FLASH_T *ProfileFlash, char *Name, void *Values, uint32_t ValuesSize, osMutexId ValuesMutex);

int32_t PROFILE_FLASH_ProfileIdxLoad(PROFILE_FLASH_T *ProfileFlash, uint32_t *ProfileIdx);
int32_t PROFILE_FLASH_ProfileIdxSave(PROFILE_FLASH_T *ProfileFlash, uint32_t ProfileIdx);

void PROFILE_FLASH_ParamsSave(PROFILE_FLASH_T *ProfileFlash);
int32_t PROFILE_FLASH_ParamsLoad(PROFILE_FLASH_T *ProfileFlash);

void PROFILE_FLASH_LangpackSave(PROFILE_FLASH_T *ProfileFlash, char *Block, uint32_t Index);
void PROFILE_FLASH_LangpackLoad(PROFILE_FLASH_T *ProfileFlash, char *Block, uint32_t Index);
void PROFILE_FLASH_LangpackClear(PROFILE_FLASH_T *ProfileFlash);

#endif /* __PROFILE_FLASH_H */
