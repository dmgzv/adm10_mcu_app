#ifndef __PROFILE_FLASH_H
#define __PROFILE_FLASH_H

/* Includes ------------------------------------------------------------------*/
#include "profile_types.h"
#include "profile.h"
#include "bsp_flash.h"

#define PROFILE_FLASH_PAGE_SIZE		BSP_FLASH_PAGE_SIZE

#define PROFILE_FLASH_CALIB_ADDR	( BSP_FLASH_CFG_ADDR )
#define	PROFILE_FLASH_CALIB_PAGES	(	PROFILE_FLASH_CALIB_MAP_PAGES + PROFILE_FLASH_CALIB_RECORDS_PAGES )
#define	PROFILE_FLASH_CALIB_SIZE	(	PROFILE_FLASH_CALIB_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CALIB_MAP_ADDR	( PROFILE_FLASH_CALIB_ADDR )
#define	PROFILE_FLASH_CALIB_MAP_PAGES	(	PROFILE_FLASH_CALIB_MAP_HEADER_PAGES + PROFILE_FLASH_CALIB_MAP_BODY_PAGES )
#define	PROFILE_FLASH_CALIB_MAP_SIZE	(	PROFILE_FLASH_CALIB_MAP_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CALIB_MAP_HEADER_ADDR		( PROFILE_FLASH_CALIB_MAP_ADDR )
#define	PROFILE_FLASH_CALIB_MAP_HEADER_PAGES	(	1 )
#define	PROFILE_FLASH_CALIB_MAP_HEADER_SIZE		(	PROFILE_FLASH_CALIB_MAP_HEADER_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CALIB_MAP_BODY_ADDR		( PROFILE_FLASH_CALIB_MAP_ADDR + PROFILE_FLASH_CALIB_MAP_HEADER_SIZE )
#define	PROFILE_FLASH_CALIB_MAP_BODY_PAGES	(	0x7F )
#define	PROFILE_FLASH_CALIB_MAP_BODY_SIZE		(	PROFILE_FLASH_CALIB_MAP_SIZE - PROFILE_FLASH_CALIB_MAP_HEADER_SIZE )

#define PROFILE_FLASH_CALIB_RECORDS_ADDR	( PROFILE_FLASH_CALIB_ADDR + PROFILE_FLASH_CALIB_MAP_SIZE )
#define	PROFILE_FLASH_CALIB_RECORDS_PAGES	(	PROFILE_FLASH_CALIB_RECORDS_CNT * PROFILE_FLASH_CALIB_RECORD_PAGES )
#define	PROFILE_FLASH_CALIB_RECORDS_SIZE	(	PROFILE_FLASH_CALIB_RECORDS_PAGES * PROFILE_FLASH_PAGE_SIZE )
#define PROFILE_FLASH_CALIB_RECORDS_CNT		( 2 )

#define PROFILE_FLASH_CALIB_RECORD_ADDR(RecordIdx)	( PROFILE_FLASH_CALIB_RECORDS_ADDR + ((RecordIdx) * PROFILE_FLASH_CALIB_RECORD_SIZE) )
#define	PROFILE_FLASH_CALIB_RECORD_PAGES						(	PROFILE_FLASH_CALIB_RECORD_HEADER_PAGES + PROFILE_FLASH_CALIB_RECORD_BODY_PAGES )
#define	PROFILE_FLASH_CALIB_RECORD_SIZE							(	PROFILE_FLASH_CALIB_RECORD_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CALIB_RECORD_HEADER_ADDR(RecordIdx)	( PROFILE_FLASH_CALIB_RECORD_ADDR(RecordIdx) )
#define	PROFILE_FLASH_CALIB_RECORD_HEADER_PAGES						(	0x01 )
#define	PROFILE_FLASH_CALIB_RECORD_HEADER_SIZE						(	PROFILE_FLASH_CALIB_RECORD_HEADER_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CALIB_RECORD_BODY_ADDR(RecordIdx)	( PROFILE_FLASH_CALIB_RECORD_HEADER_ADDR(RecordIdx) + PROFILE_FLASH_CALIB_RECORD_HEADER_SIZE )
#define	PROFILE_FLASH_CALIB_RECORD_BODY_PAGES						(	0x3F )
#define	PROFILE_FLASH_CALIB_RECORD_BODY_SIZE						(	PROFILE_FLASH_CALIB_RECORD_BODY_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIG_ADDR		( PROFILE_FLASH_CALIB_ADDR + PROFILE_FLASH_CALIB_SIZE )
#define	PROFILE_FLASH_CONFIG_PAGES	(	PROFILE_FLASH_CONFIG_MAP_PAGES + PROFILE_FLASH_CONFIG_RECORDS_PAGES )
#define	PROFILE_FLASH_CONFIG_SIZE		(	PROFILE_FLASH_CONFIG_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIG_MAP_ADDR		( PROFILE_FLASH_CONFIG_ADDR )
#define	PROFILE_FLASH_CONFIG_MAP_PAGES	(	PROFILE_FLASH_CONFIG_MAP_HEADER_PAGES + PROFILE_FLASH_CONFIG_MAP_BODY_PAGES )
#define	PROFILE_FLASH_CONFIG_MAP_SIZE		(	PROFILE_FLASH_CONFIG_MAP_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIG_MAP_HEADER_ADDR	( PROFILE_FLASH_CONFIG_MAP_ADDR )
#define	PROFILE_FLASH_CONFIG_MAP_HEADER_PAGES	(	1 )
#define	PROFILE_FLASH_CONFIG_MAP_HEADER_SIZE	(	PROFILE_FLASH_CONFIG_MAP_HEADER_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIG_MAP_BODY_ADDR	( PROFILE_FLASH_CONFIG_MAP_ADDR + PROFILE_FLASH_CONFIG_MAP_HEADER_SIZE )
#define	PROFILE_FLASH_CONFIG_MAP_BODY_PAGES	(	0x1FF )
#define	PROFILE_FLASH_CONFIG_MAP_BODY_SIZE	(	PROFILE_FLASH_CONFIG_MAP_SIZE - PROFILE_FLASH_CONFIG_MAP_HEADER_SIZE )

#define PROFILE_FLASH_CONFIG_RECORDS_ADDR		( PROFILE_FLASH_CONFIG_ADDR + PROFILE_FLASH_CONFIG_MAP_SIZE )
#define	PROFILE_FLASH_CONFIG_RECORDS_PAGES	(	PROFILE_FLASH_CONFIG_RECORDS_CNT * PROFILE_FLASH_CONFIG_RECORD_PAGES )
#define	PROFILE_FLASH_CONFIG_RECORDS_SIZE		(	PROFILE_FLASH_CONFIG_RECORDS_PAGES * PROFILE_FLASH_PAGE_SIZE )
#define PROFILE_FLASH_CONFIG_RECORDS_CNT		( 2 )

#define PROFILE_FLASH_CONFIG_RECORD_ADDR(RecordIdx)	( PROFILE_FLASH_CONFIG_RECORDS_ADDR + ((RecordIdx) * PROFILE_FLASH_CONFIG_RECORD_SIZE) )
#define	PROFILE_FLASH_CONFIG_RECORD_PAGES						(	PROFILE_FLASH_CONFIG_RECORD_HEADER_PAGES + PROFILE_FLASH_CONFIG_RECORD_BODY_PAGES )
#define	PROFILE_FLASH_CONFIG_RECORD_SIZE						(	PROFILE_FLASH_CONFIG_RECORD_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIG_RECORD_HEADER_ADDR(RecordIdx)	( PROFILE_FLASH_CONFIG_RECORD_ADDR(RecordIdx) )
#define	PROFILE_FLASH_CONFIG_RECORD_HEADER_PAGES						(	0x01 )
#define	PROFILE_FLASH_CONFIG_RECORD_HEADER_SIZE							(	PROFILE_FLASH_CONFIG_RECORD_HEADER_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIG_RECORD_BODY_ADDR(RecordIdx)	( PROFILE_FLASH_CONFIG_RECORD_HEADER_ADDR(RecordIdx) + PROFILE_FLASH_CONFIG_RECORD_HEADER_SIZE )
#define	PROFILE_FLASH_CONFIG_RECORD_BODY_PAGES						(	0x7F )
#define	PROFILE_FLASH_CONFIG_RECORD_BODY_SIZE							(	PROFILE_FLASH_CONFIG_RECORD_BODY_PAGES * PROFILE_FLASH_PAGE_SIZE )

#if ((PROFILE_FLASH_CALIB_SIZE + PROFILE_FLASH_CONFIG_SIZE) > BSP_FLASH_CFG_SIZE)
	#error Profiles headers, calibs and configs do not fit in to flash configuration section
#endif

#define PROFILE_FLASH_LANG_ADDR 	( BSP_FLASH_LANG_ADDR )
#define PROFILE_FLASH_LANG_PAGES 	( PROFILE_FLASH_LANG_SIZE / PROFILE_FLASH_PAGE_SIZE )
#define PROFILE_FLASH_LANG_SIZE 	( BSP_FLASH_LANG_SIZE )

#define PROFILE_FLASH_LANG_RECORDS_ADDR		( PROFILE_FLASH_LANG_ADDR )
#define	PROFILE_FLASH_LANG_RECORDS_PAGES	(	PROFILE_FLASH_LANG_RECORDS_SIZE / PROFILE_FLASH_PAGE_SIZE )
#define	PROFILE_FLASH_LANG_RECORDS_SIZE		(	PROFILE_FLASH_LANG_SIZE )
#define PROFILE_FLASH_LANG_RECORDS_CNT		( 2 )

#define PROFILE_FLASH_LANG_RECORD_ADDR(RecordIdx)	( PROFILE_FLASH_LANG_RECORDS_ADDR + ((RecordIdx) * PROFILE_FLASH_LANG_RECORD_SIZE) )
#define	PROFILE_FLASH_LANG_RECORD_PAGES						(	PROFILE_FLASH_LANG_RECORD_SIZE / PROFILE_FLASH_PAGE_SIZE )
#define	PROFILE_FLASH_LANG_RECORD_SIZE						(	PROFILE_FLASH_LANG_RECORDS_SIZE / PROFILE_FLASH_LANG_RECORDS_CNT )

#define PROFILE_FLASH_LANG_RECORD_HEADER_ADDR(RecordIdx)	( PROFILE_FLASH_LANG_RECORD_ADDR(RecordIdx) )
#define	PROFILE_FLASH_LANG_RECORD_HEADER_PAGES						(	1 )
#define	PROFILE_FLASH_LANG_RECORD_HEADER_SIZE							(	PROFILE_FLASH_LANG_RECORD_HEADER_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_LANG_RECORD_BODY_ADDR(RecordIdx)	( PROFILE_FLASH_LANG_RECORD_ADDR(RecordIdx) + PROFILE_FLASH_LANG_RECORD_HEADER_SIZE )
#define	PROFILE_FLASH_LANG_RECORD_BODY_PAGES						(	PROFILE_FLASH_LANG_RECORD_PAGES - PROFILE_FLASH_LANG_RECORD_HEADER_PAGES )
#define	PROFILE_FLASH_LANG_RECORD_BODY_SIZE							(	PROFILE_FLASH_LANG_RECORD_SIZE - PROFILE_FLASH_LANG_RECORD_HEADER_SIZE )

#define PROFILE_FLASH_LANG_BLOCK_SIZE			PROFILE_FLASH_PAGE_SIZE

typedef struct {
	const PROFILE_T *Profile;
	
	uint32_t CalibIdx;
	uint32_t ConfigIdx;
	uint32_t LangpackIdx;
	
	osMessageQId MessageQId;
	osThreadId ThreadId;
} PROFILE_FLASH_T;

int32_t PROFILE_FLASH_Init(PROFILE_FLASH_T *ProfileFlash, char *ThreadName, const PROFILE_T *Profile);

void PROFILE_FLASH_SaveCalibs(PROFILE_FLASH_T *ProfileFlash);
int32_t PROFILE_FLASH_LoadCalibs(PROFILE_FLASH_T *ProfileFlash);

void PROFILE_FLASH_SaveConfigs(PROFILE_FLASH_T *ProfileFlash);
int32_t PROFILE_FLASH_LoadConfigs(PROFILE_FLASH_T *ProfileFlash);

void PROFILE_FLASH_SaveParamValue(PROFILE_FLASH_T *ProfileFlash, PROFILE_PARAM_T *Param);
void PROFILE_FLASH_SaveParamColors(PROFILE_FLASH_T *ProfileFlash, PROFILE_PARAM_T *Param);

int32_t PROFILE_FLASH_LoadLangpackHeader(PROFILE_FLASH_T *ProfileFlash, uint32_t *LangpackBlocks, uint32_t *LangpackType);
int32_t PROFILE_FLASH_SaveLangpackHeader(PROFILE_FLASH_T *ProfileFlash, uint32_t LangpackBlocks, uint32_t LangpackType);
int32_t PROFILE_FLASH_LoadLangpackData(PROFILE_FLASH_T *ProfileFlash, uint32_t DataAddr, char *Data, uint32_t DataSize);
int32_t PROFILE_FLASH_SaveLangpackData(PROFILE_FLASH_T *ProfileFlash, uint32_t DataAddr, char *Data, uint32_t DataSize);

#endif /* __PROFILE_FLASH_H */
