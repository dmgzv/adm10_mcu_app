#ifndef __PROFILE_FLASH_H
#define __PROFILE_FLASH_H

/* Includes ------------------------------------------------------------------*/
#include "profile_types.h"
#include "profile.h"
#include "bsp_flash.h"

#define PROFILE_FLASH_PAGE_SIZE		BSP_FLASH_PAGE_SIZE

#define PROFILE_FLASH_HEADERS_ADDR		( BSP_FLASH_CFG_ADDR )
#define PROFILE_FLASH_HEADERS_SIZE		( PROFILE_FLASH_HEADER_SIZE * PROFILE_FLASH_HEADERS_CNT)
#define PROFILE_FLASH_HEADERS_CNT			( 2 )

#define PROFILE_FLASH_HEADER_ADDR(Idx)	( PROFILE_FLASH_HEADERS_ADDR + ((Idx) * PROFILE_FLASH_HEADER_SIZE) )
#define	PROFILE_FLASH_HEADER_PAGES			(	1 )
#define	PROFILE_FLASH_HEADER_SIZE				(	PROFILE_FLASH_HEADER_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CALIBS_ADDR		( PROFILE_FLASH_HEADERS_ADDR + PROFILE_FLASH_HEADERS_SIZE )
#define	PROFILE_FLASH_CALIBS_PAGES	(	PROFILE_FLASH_CALIBS_CNT * PROFILE_FLASH_CALIB_PAGES)
#define	PROFILE_FLASH_CALIBS_SIZE		(	PROFILE_FLASH_CALIBS_PAGES * BSP_FLASH_PAGE_SIZE )
#define PROFILE_FLASH_CALIBS_CNT		( BSP_CONFIG_PROFILES_CNT )

#define PROFILE_FLASH_CALIB_ADDR(ProfileIdx)	( PROFILE_FLASH_CALIBS_ADDR + ((ProfileIdx) * PROFILE_FLASH_CALIB_SIZE) )
#define	PROFILE_FLASH_CALIB_PAGES			(	PROFILE_FLASH_CALIB_MAP_PAGES + PROFILE_FLASH_CALIB_RECORDS_PAGES )
#define	PROFILE_FLASH_CALIB_SIZE			(	PROFILE_FLASH_CALIB_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CALIB_MAP_ADDR(ProfileIdx)	( PROFILE_FLASH_CALIB_ADDR(ProfileIdx) )
#define	PROFILE_FLASH_CALIB_MAP_PAGES			(	PROFILE_FLASH_CALIB_MAP_HEADER_PAGES + PROFILE_FLASH_CALIB_MAP_BODY_PAGES )
#define	PROFILE_FLASH_CALIB_MAP_SIZE			(	PROFILE_FLASH_CALIB_MAP_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CALIB_MAP_HEADER_ADDR(ProfileIdx)	( PROFILE_FLASH_CALIB_MAP_ADDR(ProfileIdx) )
#define	PROFILE_FLASH_CALIB_MAP_HEADER_PAGES		(	1 )
#define	PROFILE_FLASH_CALIB_MAP_HEADER_SIZE			(	PROFILE_FLASH_CALIB_MAP_HEADER_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CALIB_MAP_BODY_ADDR(ProfileIdx)	( PROFILE_FLASH_CALIB_MAP_ADDR(ProfileIdx) + PROFILE_FLASH_CALIB_MAP_HEADER_SIZE )
#define	PROFILE_FLASH_CALIB_MAP_BODY_PAGES		(	6 )
#define	PROFILE_FLASH_CALIB_MAP_BODY_SIZE			(	PROFILE_FLASH_CALIB_MAP_SIZE - PROFILE_FLASH_CALIB_MAP_HEADER_SIZE )

#define PROFILE_FLASH_CALIB_RECORDS_ADDR(ProfileIdx)	( PROFILE_FLASH_CALIB_ADDR(ProfileIdx) + PROFILE_FLASH_CALIB_MAP_SIZE )
#define	PROFILE_FLASH_CALIB_RECORDS_PAGES			(	PROFILE_FLASH_CALIB_RECORDS_CNT * PROFILE_FLASH_CALIB_RECORD_PAGES )
#define	PROFILE_FLASH_CALIB_RECORDS_SIZE			(	PROFILE_FLASH_CALIB_RECORDS_PAGES * PROFILE_FLASH_PAGE_SIZE )
#define PROFILE_FLASH_CALIB_RECORDS_CNT				( 2 )

#define PROFILE_FLASH_CALIB_RECORD_ADDR(ProfileIdx, RecordIdx)	( PROFILE_FLASH_CALIB_RECORDS_ADDR(ProfileIdx) + ((RecordIdx) * PROFILE_FLASH_CALIB_RECORD_SIZE) )
#define	PROFILE_FLASH_CALIB_RECORD_PAGES			(	PROFILE_FLASH_CALIB_RECORD_HEADER_PAGES + PROFILE_FLASH_CALIB_RECORD_BODY_PAGES )
#define	PROFILE_FLASH_CALIB_RECORD_SIZE				(	PROFILE_FLASH_CALIB_RECORD_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CALIB_RECORD_HEADER_ADDR(ProfileIdx, RecordIdx)	( PROFILE_FLASH_CALIB_RECORD_ADDR(ProfileIdx, RecordIdx) )
#define	PROFILE_FLASH_CALIB_RECORD_HEADER_PAGES		(	1 )
#define	PROFILE_FLASH_CALIB_RECORD_HEADER_SIZE		(	PROFILE_FLASH_CALIB_RECORD_HEADER_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CALIB_RECORD_BODY_ADDR(ProfileIdx, RecordIdx)	( PROFILE_FLASH_CALIB_RECORD_HEADER_ADDR((ProfileIdx), (RecordIdx)) + PROFILE_FLASH_CALIB_RECORD_HEADER_SIZE )
#define	PROFILE_FLASH_CALIB_RECORD_BODY_PAGES			(	6 )
#define	PROFILE_FLASH_CALIB_RECORD_BODY_SIZE			(	PROFILE_FLASH_CALIB_RECORD_BODY_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIGS_ADDR		( PROFILE_FLASH_CALIBS_ADDR + PROFILE_FLASH_CALIBS_SIZE )
#define	PROFILE_FLASH_CONFIGS_PAGES		(	PROFILE_FLASH_CONFIGS_CNT * PROFILE_FLASH_CONFIG_PAGES)
#define	PROFILE_FLASH_CONFIGS_SIZE		(	PROFILE_FLASH_CONFIGS_PAGES * BSP_FLASH_PAGE_SIZE )
#define PROFILE_FLASH_CONFIGS_CNT			( BSP_CONFIG_PROFILES_CNT )

#define PROFILE_FLASH_CONFIG_ADDR(ProfileIdx)	( PROFILE_FLASH_CONFIGS_ADDR + ((ProfileIdx) * PROFILE_FLASH_CONFIG_SIZE) )
#define	PROFILE_FLASH_CONFIG_PAGES		(	PROFILE_FLASH_CONFIG_MAP_PAGES + PROFILE_FLASH_CONFIG_RECORDS_PAGES )
#define	PROFILE_FLASH_CONFIG_SIZE			(	PROFILE_FLASH_CONFIG_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIG_MAP_ADDR(ProfileIdx)	( PROFILE_FLASH_CONFIG_ADDR(ProfileIdx) )
#define	PROFILE_FLASH_CONFIG_MAP_PAGES		(	PROFILE_FLASH_CONFIG_MAP_HEADER_PAGES + PROFILE_FLASH_CONFIG_MAP_BODY_PAGES )
#define	PROFILE_FLASH_CONFIG_MAP_SIZE			(	PROFILE_FLASH_CONFIG_MAP_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIG_MAP_HEADER_ADDR(ProfileIdx)	( PROFILE_FLASH_CONFIG_MAP_ADDR(ProfileIdx) )
#define	PROFILE_FLASH_CONFIG_MAP_HEADER_PAGES		(	1 )
#define	PROFILE_FLASH_CONFIG_MAP_HEADER_SIZE		(	PROFILE_FLASH_CONFIG_MAP_HEADER_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIG_MAP_BODY_ADDR(ProfileIdx)	( PROFILE_FLASH_CONFIG_MAP_ADDR(ProfileIdx) + PROFILE_FLASH_CONFIG_MAP_HEADER_SIZE )
#define	PROFILE_FLASH_CONFIG_MAP_BODY_PAGES		(	110 )
#define	PROFILE_FLASH_CONFIG_MAP_BODY_SIZE		(	PROFILE_FLASH_CONFIG_MAP_SIZE - PROFILE_FLASH_CONFIG_MAP_HEADER_SIZE )

#define PROFILE_FLASH_CONFIG_RECORDS_ADDR(ProfileIdx)	( PROFILE_FLASH_CONFIG_ADDR(ProfileIdx) + PROFILE_FLASH_CONFIG_MAP_SIZE )
#define	PROFILE_FLASH_CONFIG_RECORDS_PAGES		(	PROFILE_FLASH_CONFIG_RECORDS_CNT * PROFILE_FLASH_CONFIG_RECORD_PAGES )
#define	PROFILE_FLASH_CONFIG_RECORDS_SIZE			(	PROFILE_FLASH_CONFIG_RECORDS_PAGES * PROFILE_FLASH_PAGE_SIZE )
#define PROFILE_FLASH_CONFIG_RECORDS_CNT			( 2 )

#define PROFILE_FLASH_CONFIG_RECORD_ADDR(ProfileIdx, RecordIdx)	( PROFILE_FLASH_CONFIG_RECORDS_ADDR(ProfileIdx) + ((RecordIdx) * PROFILE_FLASH_CONFIG_RECORD_SIZE) )
#define	PROFILE_FLASH_CONFIG_RECORD_PAGES			(	PROFILE_FLASH_CONFIG_RECORD_HEADER_PAGES + PROFILE_FLASH_CONFIG_RECORD_BODY_PAGES )
#define	PROFILE_FLASH_CONFIG_RECORD_SIZE			(	PROFILE_FLASH_CONFIG_RECORD_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIG_RECORD_HEADER_ADDR(ProfileIdx, RecordIdx)	( PROFILE_FLASH_CONFIG_RECORD_ADDR(ProfileIdx, RecordIdx) )
#define	PROFILE_FLASH_CONFIG_RECORD_HEADER_PAGES		(	1 )
#define	PROFILE_FLASH_CONFIG_RECORD_HEADER_SIZE			(	PROFILE_FLASH_CONFIG_RECORD_HEADER_PAGES * PROFILE_FLASH_PAGE_SIZE )

#define PROFILE_FLASH_CONFIG_RECORD_BODY_ADDR(ProfileIdx, RecordIdx)	( PROFILE_FLASH_CONFIG_RECORD_HEADER_ADDR((ProfileIdx), (RecordIdx)) + PROFILE_FLASH_CONFIG_RECORD_HEADER_SIZE )
#define	PROFILE_FLASH_CONFIG_RECORD_BODY_PAGES		(	60 )
#define	PROFILE_FLASH_CONFIG_RECORD_BODY_SIZE			(	PROFILE_FLASH_CONFIG_RECORD_BODY_PAGES * PROFILE_FLASH_PAGE_SIZE )

#if ((PROFILE_FLASH_HEADERS_SIZE + PROFILE_FLASH_CALIBS_SIZE + PROFILE_FLASH_CONFIGS_SIZE) > BSP_FLASH_CFG_SIZE)
	#error Profiles headers, calibs and configs do not fit in to flash configuration section
#endif

#define PROFILE_FLASH_LANGS_ADDR 	( BSP_FLASH_LANG_ADDR )
#define PROFILE_FLASH_LANGS_SIZE 	( BSP_FLASH_LANG_SIZE )
#define PROFILE_FLASH_LANGS_CNT		( BSP_CONFIG_PROFILES_CNT )

#define PROFILE_FLASH_LANG_ADDR(ProfileIdx) ( PROFILE_FLASH_LANGS_ADDR + ((ProfileIdx) * PROFILE_FLASH_LANG_SIZE) )
#define	PROFILE_FLASH_LANG_SIZE							(	PROFILE_FLASH_LANGS_SIZE / PROFILE_FLASH_LANGS_CNT )
	
typedef struct {
	PROFILE_T *Profile;
	
	uint32_t HeaderIdx;
	uint32_t CalibIdx;
	uint32_t ConfigIdx;
	
	uint32_t SaveEnable;
	
	osMessageQId MessageQId;
	osThreadId ThreadId;
} PROFILE_FLASH_T;

int32_t PROFILE_FLASH_Init(PROFILE_FLASH_T *ProfileFlash, char *ThreadName, PROFILE_T *Profile);

int32_t PROFILE_FLASH_SaveProfileIdx(PROFILE_FLASH_T *ProfileFlash, uint32_t ProfileIdx);

int32_t PROFILE_FLASH_InitCalibs(PROFILE_FLASH_T *ProfileFlash);
void PROFILE_FLASH_SaveCalibs(PROFILE_FLASH_T *ProfileFlash);

int32_t PROFILE_FLASH_InitConfigs(PROFILE_FLASH_T *ProfileFlash);
void PROFILE_FLASH_SaveConfigs(PROFILE_FLASH_T *ProfileFlash);

void PROFILE_FLASH_SaveValue(PROFILE_FLASH_T *ProfileFlash, uint8_t Table, uint16_t Idx);

void PROFILE_FLASH_LangpackSave(PROFILE_FLASH_T *ProfileFlash, char *Block, uint32_t Index);
void PROFILE_FLASH_LangpackLoad(PROFILE_FLASH_T *ProfileFlash, char *Block, uint32_t Index);
void PROFILE_FLASH_LangpackClear(PROFILE_FLASH_T *ProfileFlash);

#endif /* __PROFILE_FLASH_H */
