		PROFILE_SetFactoryAlarmColors(Profile, PROFILE_TABLE_2, ProfileADM10DynamicLnSFPStateIdx[Idx]);
		PROFILE_SetFactoryAlarmColors(Profile, PROFILE_TABLE_2, ProfileADM10DynamicLnSFPTempIdx[Idx]);
		PROFILE_SetFactoryAlarmColors(Profile, PROFILE_TABLE_2, ProfileADM10DynamicLnSFPRxPwrIdx[Idx]);
		PROFILE_SetFactoryAlarmColors(Profile, PROFILE_TABLE_2, ProfileADM10DynamicLnSFPTxPwrIdx[Idx]);
