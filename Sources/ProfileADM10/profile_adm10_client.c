			EnableTx = PROFILE_ADM10_CL_SFP_ENABLE_TX_ENUM_DISABLED;
			PROFILE_SetValue(Profile, PROFILE_TABLE_3, ProfileADM10ConfigClSFPEnableTxIdx[Idx + 1], &EnableTx);
