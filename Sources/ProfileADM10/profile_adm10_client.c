				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPTxPwrIdx[Idx][2], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.TxPwr[SFP_THR_WMAX]);
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPTxPwrIdx[Idx][3], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.TxPwr[SFP_THR_CMAX]);
				
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPTempIdx[Idx][0], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.Temp[SFP_THR_CMIN]);
