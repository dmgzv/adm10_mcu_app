static void PROFILE_ADM10_CLIENT_UpdateInfoAndStaticValues(PROFILE_T *Profile, uint32_t Idx)
{
	char Tmp[PROFILE_STRING_MAX_LEN];
	uint32_t UpdateFlag;
	uint32_t State;
	float __Freq, __MinFreq, __MaxFreq, __FreqSp;
	uint32_t Freq, MinFreq, MaxFreq, FreqSp;
	
	if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADM10ConfigClSetStateIdx[Idx], &State))
		return;
	
	switch (BSP_DEV_GET_STATE(&sfp[BSP_SFP_CLIENT_IDX(Idx)]))
	{
		case BSP_DEV_STATE_OK:
			//Check if inserted module is same as previous
			UpdateFlag = 1;
			if (PROFILE_GetValue(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPVendorIdx[Idx], Tmp))
				return;
			if (!strncmp(Tmp, sfp[BSP_SFP_CLIENT_IDX(Idx)].Info.Vendor, sizeof(sfp[BSP_SFP_CLIENT_IDX(Idx)].Info.Vendor)))
			{
				if (PROFILE_GetValue(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPSrNumberIdx[Idx], Tmp))
					return;
				if (!strncmp(Tmp, sfp[BSP_SFP_CLIENT_IDX(Idx)].Info.SerialNumber, sizeof(sfp[BSP_SFP_CLIENT_IDX(Idx)].Info.SerialNumber)))
				{
					if (PROFILE_GetValue(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPPtNumberIdx[Idx], Tmp))
						return;
					if (!strncmp(Tmp, sfp[BSP_SFP_CLIENT_IDX(Idx)].Info.PartNumber, sizeof(sfp[BSP_SFP_CLIENT_IDX(Idx)].Info.PartNumber)))
					{
						UpdateFlag = 0;
					}
				}
			}
			//If module is not the same as previous, then update info and thresholds values
			if (UpdateFlag)
			{
				if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADM10ConfigClSFPSetFreqIdx[Idx], &__Freq))
					return;
				
				PROFILE_SetValue(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPVendorIdx[Idx], sfp[BSP_SFP_CLIENT_IDX(Idx)].Info.Vendor);
				PROFILE_SetValue(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPSrNumberIdx[Idx], sfp[BSP_SFP_CLIENT_IDX(Idx)].Info.SerialNumber);
				PROFILE_SetValue(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPPtNumberIdx[Idx], sfp[BSP_SFP_CLIENT_IDX(Idx)].Info.PartNumber);
				
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPRxPwrIdx[Idx][0], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.RxPwr[SFP_THR_CMIN]);
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPRxPwrIdx[Idx][1], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.RxPwr[SFP_THR_WMIN]);
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPRxPwrIdx[Idx][2], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.RxPwr[SFP_THR_WMAX]);
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPRxPwrIdx[Idx][3], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.RxPwr[SFP_THR_CMAX]);
				
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPTxPwrIdx[Idx][0], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.TxPwr[SFP_THR_CMIN]);
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPTxPwrIdx[Idx][1], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.TxPwr[SFP_THR_WMIN]);
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPTxPwrIdx[Idx][2], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.TxPwr[SFP_THR_WMAX]);
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPTxPwrIdx[Idx][3], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.TxPwr[SFP_THR_CMAX]);
				
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPTempIdx[Idx][0], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.Temp[SFP_THR_CMIN]);
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPTempIdx[Idx][1], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.Temp[SFP_THR_WMIN]);
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPTempIdx[Idx][2], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.Temp[SFP_THR_WMAX]);
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPTempIdx[Idx][3], &sfp[BSP_SFP_CLIENT_IDX(Idx)].Thr.Temp[SFP_THR_CMAX]);
				
				MinFreq = sfp[BSP_SFP_CLIENT_IDX(Idx)].Freq.Min;
				MaxFreq = sfp[BSP_SFP_CLIENT_IDX(Idx)].Freq.Max;
				FreqSp = sfp[BSP_SFP_CLIENT_IDX(Idx)].Freq.Spacing;
				Freq = __Freq * 1000000;
				
				__MinFreq = MinFreq / 1000000.0f;
				__MaxFreq = MaxFreq / 1000000.0f;
				__FreqSp = FreqSp / 1000.0f;
				PROFILE_SetValue(Profile, PROFILE_TABLE_3, ProfileADM10ConfigClSFPSetFreqSpIdx[Idx], &__FreqSp);				
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPSetFreqIdx[Idx][0], &__MinFreq);
				PROFILE_SetValue(Profile, PROFILE_TABLE_4, ProfileADM10StaticClSFPSetFreqIdx[Idx][1], &__MaxFreq);
				if ((Freq < MinFreq) || (Freq > MaxFreq) || (Freq % FreqSp))
				{
					PROFILE_SetValue(Profile, PROFILE_TABLE_3, ProfileADM10ConfigClSFPSetFreqIdx[Idx], &__MinFreq);
				}
				
				PROFILE_FLASH_ConfigsSave(&Profile->ProfileFlash);
			}
			PROFILE_SetState(Profile, PROFILE_TABLE_1, ProfileADM10InfoClDestinationIdx[Idx], State);
			PROFILE_SetState(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPVendorIdx[Idx], State);
			PROFILE_SetState(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPSrNumberIdx[Idx], State);
			PROFILE_SetState(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPPtNumberIdx[Idx], State);
			break;
		case BSP_DEV_STATE_RESET:
		case BSP_DEV_STATE_INIT:
		case BSP_DEV_STATE_FAIL:
		default:
			PROFILE_SetState(Profile, PROFILE_TABLE_1, ProfileADM10InfoClDestinationIdx[Idx], State);
			PROFILE_SetState(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPVendorIdx[Idx], PROFILE_STATE_OOS);
			PROFILE_SetState(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPSrNumberIdx[Idx], PROFILE_STATE_OOS);
			PROFILE_SetState(Profile, PROFILE_TABLE_1, ProfileADM10InfoClSFPPtNumberIdx[Idx], PROFILE_STATE_OOS);
			break;
	}
}

