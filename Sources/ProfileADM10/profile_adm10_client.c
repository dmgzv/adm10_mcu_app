static int32_t PROFILE_ADM10_CLIENT_CheckClSetStateValue(PROFILE_T *Profile, uint8_t Table, uint16_t TableIdx, void *Value, uint32_t Idx)
{
	uint32_t Mode;
	uint32_t SetState;
	uint32_t DataType;
	
	/* Do not alow to go from OOS to IS */
	if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADM10ConfigClSetStateIdx[Idx], &SetState))
		return -1;
	
	if ((SetState == PROFILE_STATE_OOS) && (*(uint32_t*)Value == PROFILE_STATE_IS))
		return -1;
	
	if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, PROFILE_ADM10_SETMODE_IDX, &Mode))
		return -1;
	
	if ((Idx % 2) == 0)
		return 0;
	
	if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADM10ConfigClSetDataTypeIdx[Idx - 1], &DataType))
		return -1;
	
	if (DataType != 130)
		return 0;
	
	if (*(uint32_t*)Value != PROFILE_STATE_OOS)
		return -1;
	
	return 0;
}

static int32_t PROFILE_ADM10_CLIENT_CheckClSFPEnableTxValue(PROFILE_T *Profile, uint8_t Table, uint16_t TableIdx, void *Value, uint32_t Idx)
{
	uint32_t SetState;
	
	/* Do not alow to enable tx if set state if OOS */
	if (*(uint32_t*)Value == 1)
	{
		if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADM10ConfigClSetStateIdx[Idx], &SetState))
			return -1;
		if (SetState == PROFILE_STATE_OOS)
			return -1;
	}
	return 0;
}

