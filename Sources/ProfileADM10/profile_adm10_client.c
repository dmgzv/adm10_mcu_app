	{
		State = PROFILE_ADM10_CL_SET_STATE_ENUM_OOS;
		Defects = 0;
		Errors = 0;
		PERF_Reset(&ClODU1Perf[Idx]);
	}
	PROFILE_UpdateParam(Profile, PROFILE_TABLE_8, ProfileADM10PerfClODU1EBIdx[Idx], &ClODU1Perf[Idx].EB, State);
