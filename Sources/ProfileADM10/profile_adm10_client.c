static void PROFILE_ADM10_CLIENT_UpdateAlarmLedValue(PROFILE_T *Profile, uint32_t Idx)
{
	uint32_t i, LedColor;
	uint8_t Color, ParamColor, ParamState;
	uint8_t State;
	
	if (PROFILE_ADM10_CLIENT_GetState(Profile, Idx, &State))
		return;
	if (State == PROFILE_STATE_IS)
	{
		Color = PROFILE_COLOR_NORMAL;
		
		PROFILE_GetColor(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClSFPStateIdx[Idx], &ParamColor);
		PROFILE_GetState(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClSFPStateIdx[Idx], &ParamState);
		if ((ParamState == PROFILE_STATE_IS) && (Color < ParamColor))
			Color = ParamColor;
		
		PROFILE_GetColor(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClSFPTempIdx[Idx], &ParamColor);
		PROFILE_GetState(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClSFPTempIdx[Idx], &ParamState);
		if ((ParamState == PROFILE_STATE_IS) && (Color < ParamColor))
			Color = ParamColor;
		
		PROFILE_GetColor(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClSFPRxPwrIdx[Idx], &ParamColor);
		PROFILE_GetState(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClSFPRxPwrIdx[Idx], &ParamState);
		if ((ParamState == PROFILE_STATE_IS) && (Color < ParamColor))
			Color = ParamColor;
		
		PROFILE_GetColor(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClSFPTxPwrIdx[Idx], &ParamColor);
		PROFILE_GetState(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClSFPTxPwrIdx[Idx], &ParamState);
		if ((ParamState == PROFILE_STATE_IS) && (Color < ParamColor))
			Color = ParamColor;
		
		PROFILE_GetColor(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClSDHRSAlarmsIdx[Idx], &ParamColor);
		PROFILE_GetState(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClSDHRSAlarmsIdx[Idx], &ParamState);
		if ((ParamState == PROFILE_STATE_IS) && (Color < ParamColor))
			Color = ParamColor;
		
		PROFILE_GetColor(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClEthAlarmsIdx[Idx], &ParamColor);
		PROFILE_GetState(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClEthAlarmsIdx[Idx], &ParamState);
		if ((ParamState == PROFILE_STATE_IS) && (Color < ParamColor))
			Color = ParamColor;
		
		PROFILE_GetColor(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClOTU1AlarmsIdx[Idx], &ParamColor);
		PROFILE_GetState(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClOTU1AlarmsIdx[Idx], &ParamState);
		if ((ParamState == PROFILE_STATE_IS) && (Color < ParamColor))
			Color = ParamColor;
		
		PROFILE_GetColor(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClODU1AlarmsIdx[Idx], &ParamColor);
		PROFILE_GetState(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClODU1AlarmsIdx[Idx], &ParamState);
		if ((ParamState == PROFILE_STATE_IS) && (Color < ParamColor))
			Color = ParamColor;
		
		PROFILE_GetColor(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClOPU1AlarmsIdx[Idx], &ParamColor);
		PROFILE_GetState(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClOPU1AlarmsIdx[Idx], &ParamState);
		if ((ParamState == PROFILE_STATE_IS) && (Color < ParamColor))
			Color = ParamColor;
		
		for (i = 0; i < PROFILE_ADM10_CLIENT_PORT_ODU0S; i++)
		{
			PROFILE_GetColor(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClODU0AlarmsIdx[Idx][i], &ParamColor);
			PROFILE_GetState(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClODU0AlarmsIdx[Idx][i], &ParamState);
			if ((ParamState == PROFILE_STATE_IS) && (Color < ParamColor))
				Color = ParamColor;
			
			PROFILE_GetColor(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClOPU0AlarmsIdx[Idx][i], &ParamColor);
			PROFILE_GetState(Profile, PROFILE_TABLE_2, ProfileADM10DynamicClOPU0AlarmsIdx[Idx][i], &ParamState);
			if ((ParamState == PROFILE_STATE_IS) && (Color < ParamColor))
				Color = ParamColor;
		}
		
		if (Color == 7)
		{
			BSP_SFP_PIN_SetAlarmLed(BSP_SFP_CLIENT_IDX(Idx), BSP_SFP_PIN_LED_RED);
			LedColor = 2;
			PROFILE_SetValue(Profile, PROFILE_TABLE_5, ProfileADM10LedClAlarmIdx[Idx], &LedColor);
		}
		else if ((Color > 3) && (Color < 7))
		{
			BSP_SFP_PIN_SetAlarmLed(BSP_SFP_CLIENT_IDX(Idx), BSP_SFP_PIN_LED_YELLOW);
			LedColor = 3;
			PROFILE_SetValue(Profile, PROFILE_TABLE_5, ProfileADM10LedClAlarmIdx[Idx], &LedColor);
		}
		else if (Color == 3)
		{
			BSP_SFP_PIN_SetAlarmLed(BSP_SFP_CLIENT_IDX(Idx), BSP_SFP_PIN_LED_GREEN);
			LedColor = 1;
			PROFILE_SetValue(Profile, PROFILE_TABLE_5, ProfileADM10LedClAlarmIdx[Idx], &LedColor);
		}
		else
		{
			BSP_LED_Set(BSP_LED_TYPE_ALARM, BSP_LED_COLOR_NO);
			LedColor = 0;
			PROFILE_SetValue(Profile, PROFILE_TABLE_5, ProfileADM10LedClAlarmIdx[Idx], &LedColor);
		}
	}
	else
	{
		BSP_SFP_PIN_SetAlarmLed(BSP_SFP_CLIENT_IDX(Idx), BSP_SFP_PIN_LED_OFF);
		LedColor = 0;
		PROFILE_SetValue(Profile, PROFILE_TABLE_5, ProfileADM10LedClAlarmIdx[Idx], &LedColor);
	}
}

