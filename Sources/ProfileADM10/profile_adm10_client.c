static int32_t PROFILE_ADM10_CLIENT_CheckClSetStateValue(PROFILE_T *Profile, uint8_t Table, uint16_t TableIdx, void *Value, uint32_t Idx)
{
	uint32_t Mode;
	uint32_t SetState;
	uint32_t DataType;
	
	/* Do not alow to go from OOS to IS */
	if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADM10ConfigClSetStateIdx[Idx], &SetState))
		return -1;
	
	if ((SetState == PROFILE_ADM10_CL_SET_STATE_ENUM_OOS) && ((*(uint32_t*)Value == PROFILE_ADM10_CL_SET_STATE_ENUM_IS) || (*(uint32_t*)Value == PROFILE_ADM10_CL_SET_STATE_ENUM_AINS)))
		return -1;
	
	if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, PROFILE_ADM10_SETMODE_IDX, &Mode))
		return -1;
	
	if ((Mode == PROFILE_ADM10_SET_MODE_ENUM_ADM_10) || (Mode == PROFILE_ADM10_SET_MODE_ENUM_AGG_2X10BS))
	{
		if ((Idx % 2) == 0)
			return 0;
		
		if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADM10ConfigClSetDataTypeIdx[Idx - 1], &DataType))
			return -1;
		
		if (DataType != PROFILE_ADM10_CL_SET_DATA_TYPE_ENUM_STM16)
			return 0;
		
		if (*(uint32_t*)Value != PROFILE_ADM10_CL_SET_STATE_ENUM_OOS)
			return -1;
	}
	else if (Mode == PROFILE_ADM10_SET_MODE_ENUM_AGG_10BS_ADM_2_5)
	{
		if (Idx < 8)
		{
			if ((Idx % 2) == 0)
				return 0;
			
			if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADM10ConfigClSetDataTypeIdx[Idx - 1], &DataType))
				return -1;
			
			if (DataType != PROFILE_ADM10_CL_SET_DATA_TYPE_ENUM_STM16)
				return 0;
			
			if (*(uint32_t*)Value != PROFILE_ADM10_CL_SET_STATE_ENUM_OOS)
				return -1;
		}
	}
	
	return 0;
}

