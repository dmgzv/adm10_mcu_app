void PROFILE_ADM_LINE_UpdateConfigs(PROFILE_T *Profile)
{
	uint32_t i, j;
	uint32_t State, SFPEnableTx, Loopback, FECType, ALSMode;
	uint32_t OPU2PayloadType;
	uint32_t OPU1PayloadType[4];
	float SFPSetFreq;
	uint32_t RxLos;
	
	for (i = 0; i < PROFILE_ADM_LINE_PORTS; i++)
	{
		if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADMConfigLnSetStateIdx[i], &State))
			return;
		if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADMConfigLnSFPEnableTxIdx[i], &SFPEnableTx))
			return;
		if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADMConfigLnSFPSetFreqIdx[i], &SFPSetFreq))
			return;
		if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADMConfigLnOTU2SetFECTypeIdx[i], &FECType))
			return;
		if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADMConfigLnOPU2SetPayloadIdx[i], &OPU2PayloadType))
			return;
		if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADMConfigLnSetLoopbackIdx[i], &Loopback))
			return;
		if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADMConfigLnSetALSModeIdx[i], &ALSMode))
			return;
		for (j = 0; j < 4; j++)
		{
			if (PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADMConfigLnOPU1SetPayloadIdx[i][j], &OPU1PayloadType[j]))
				return;
		}
		
		SFP_ConfigFreq(&sfp[BSP_SFP_LINE_IDX(i)], SFPSetFreq * 1000000);
		SFP_ConfigRateSel(&sfp[BSP_SFP_LINE_IDX(i)], 1);
		
		if (ALSMode == 1)
		{
			RxLos = 0;
			if ((BSP_DEV_GET_STATE(&fpga_line) != BSP_DEV_STATE_OK) || \
				(BSP_DEV_GET_STATE(&sfp[BSP_SFP_LINE_IDX(i)]) != BSP_DEV_STATE_OK) || \
				sfp[BSP_SFP_LINE_IDX(i)].Pin.RxLos || \
				(fpga_line.Iface[i].__PMAStatus & BSP_FPGA_LINE_IFACE_PMASTATUS_RX_LOS_MASK))
			{
				RxLos = 1;
			}
			ALS_Update(&LnALS[i], ALS_STATE_ENABLED, SFPEnableTx, RxLos, 100, 5);
			SFP_ConfigTxDisable(&sfp[BSP_SFP_LINE_IDX(i)], LnALS[i].TxEnable ? 0 : 1);
		}
		else
		{
			RxLos = 0;
			ALS_Update(&LnALS[i], ALS_STATE_DISABLED, SFPEnableTx, RxLos, 100, 5);
			SFP_ConfigTxDisable(&sfp[BSP_SFP_LINE_IDX(i)], SFPEnableTx ? 0 : 1);
		}		
		
		if (Loopback == 0)
		{
			BSP_FPGA_LINE_LOOPBACK_SET(i, BSP_FPGA_LINE_LOOPBACK_NO);
		}
		else if (Loopback == 1)
		{
			BSP_FPGA_LINE_LOOPBACK_SET(i, BSP_FPGA_LINE_LOOPBACK_POST_CDR);
		}
		else if (Loopback == 2)
		{
			BSP_FPGA_LINE_LOOPBACK_SET(i, BSP_FPGA_LINE_LOOPBACK_SERIAL);
		}
		
		if (FECType == 1)
		{
			BSP_FPGA_LINE_IFACE_CTRL_SET(i, BSP_FPGA_LINE_IFACE_CTRL_FEC_DISABLED_MASK | BSP_FPGA_LINE_IFACE_CTRL_CNTR_EN_MASK);
		}
		else
		{
			BSP_FPGA_LINE_IFACE_CTRL_SET(i, BSP_FPGA_LINE_IFACE_CTRL_CNTR_EN_MASK);
		}
	}
}

