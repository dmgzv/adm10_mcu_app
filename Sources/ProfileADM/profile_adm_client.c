int32_t PROFILE_ADM_CLIENT_CheckConfigValue(PROFILE_T *Profile, uint8_t Table, uint16_t TableIdx, void *Value)
{
	uint32_t i;
	
	for (i = 0; i < PROFILE_ADM_CLIENT_PORTS; i++)
	{
		if (TableIdx == ProfileADMConfigClSetStateIdx[i])
		{
			if (PROFILE_ADM_CLIENT_CheckClSetStateValue(Profile, Table, TableIdx, Value, i))
				return -1;
			return 0;
		}
		if (TableIdx == ProfileADMConfigClSFPEnableTxIdx[i])
		{
			if (PROFILE_ADM_CLIENT_CheckClSFPEnableTxValue(Profile, Table, TableIdx, Value, i))
				return -1;
			return 0;
		}
		if (TableIdx == ProfileADMConfigClSetLoopbackIdx[i])
		{
			if (PROFILE_ADM_CLIENT_CheckClSetLoopbackValue(Profile, Table, TableIdx, Value, i))
				return -1;
			return 0;
		}
		if (TableIdx == ProfileADMConfigClSFPSetFreqIdx[i])
		{
			if (PROFILE_ADM_CLIENT_CheckClSFPSetFreqValue(Profile, Table, TableIdx, Value, i))
				return -1;
			return 0;
		}
		if (TableIdx == ProfileADMConfigClSFPSetFreqSpIdx[i])
		{
			if (PROFILE_ADM_CLIENT_CheckClSFPSetFreqSpValue(Profile, Table, TableIdx, Value, i))
				return -1;
			return 0;
		}
		if (TableIdx == ProfileADMConfigClSetDataTypeIdx[i])
		{
			if (PROFILE_ADM_CLIENT_CheckClSetDataTypeValue(Profile, Table, TableIdx, Value, i))
				return -1;
			return 0;
		}
	}
	return 0;
}

