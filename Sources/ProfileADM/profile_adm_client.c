	PROFILE_UpdateParam(Profile, PROFILE_TABLE_8, ProfileADMPerfClEthRxOctsIdx[Idx], &ClEthRxOcts[Idx], PROFILE_COLOR_TYPE_NO, State);
	PROFILE_UpdateParam(Profile, PROFILE_TABLE_8, ProfileADMPerfClEthRxErrsIdx[Idx], &ClEthRxErrs[Idx], PROFILE_COLOR_TYPE_NO, State);
	PROFILE_UpdateParam(Profile, PROFILE_TABLE_8, ProfileADMPerfClEthTxPktsIdx[Idx], &ClEthTxPkts[Idx], PROFILE_COLOR_TYPE_NO, State);
	PROFILE_UpdateParam(Profile, PROFILE_TABLE_8, ProfileADMPerfClEthTxOctsIdx[Idx], &ClEthTxOcts[Idx], PROFILE_COLOR_TYPE_NO, State);
