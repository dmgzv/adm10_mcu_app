static int32_t PROFILE_ADM_CLIENT_CheckClSetStateValue(PROFILE_T *Profile, uint8_t Table, uint16_t TableIdx, void *Value, uint32_t Idx)
{
	uint32_t SetState;
	
	/* Do not alow to go from OOS to IS */
	PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADMConfigClSetStateIdx[Idx], &SetState);
	if ((SetState == PROFILE_STATE_OOS) && (*(uint32_t*)Value == PROFILE_STATE_IS))
		return -1;
	return 0;
}

static int32_t PROFILE_ADM_CLIENT_CheckClSFPEnableTxValue(PROFILE_T *Profile, uint8_t Table, uint16_t TableIdx, void *Value, uint32_t Idx)
{
	uint32_t SetState;
	
	/* Do not alow to enable tx if set state if OOS */
	if (*(uint32_t*)Value == 1)
	{
		PROFILE_GetValue(Profile, PROFILE_TABLE_3, ProfileADMConfigClSetStateIdx[Idx], &SetState);
		if (SetState == PROFILE_STATE_OOS)
			return -1;
	}
	return 0;
}

int32_t PROFILE_ADM_CLIENT_CheckConfigValue(PROFILE_T *Profile, uint8_t Table, uint16_t TableIdx, void *Value)
{
	uint32_t i;
	
	for (i = 0; i < PROFILE_ADM_CLIENT_PORTS; i++)
	{
		if (TableIdx == ProfileADMConfigClSetStateIdx[i])
		{
			if (PROFILE_ADM_CLIENT_CheckClSetStateValue(Profile, Table, TableIdx, Value, i))
				return -1;
			return 0;
		}
		if (TableIdx == ProfileADMConfigClSFPEnableTxIdx[i])
		{
			if (PROFILE_ADM_CLIENT_CheckClSFPEnableTxValue(Profile, Table, TableIdx, Value, i))
				return -1;
			return 0;
		}
	}
	return 0;
}

